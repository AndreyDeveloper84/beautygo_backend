"""Переход `unmapped → review_required` — один дом на всех, кто его делает (DRF-2429).

Правило владельца (`OPEN_DECISIONS.md` §76): связь есть, доказуемого провенанса
нет → ``REVIEW_REQUIRED``; связи нет → остаётся ``UNMAPPED``; ``VERIFIED`` —
никому. Разово его прогнала миграция ``services/0017_mapping_status_backfill``
08.09, и там же он жил.

# Зачем у правила появился дом

Строки сида заводятся со статусом ``unmapped`` (сид его не ставит вовсе), а
правило связи демо-услуг (``confirm_seeded_links``, DRF-2408) берёт только
``review_required``. Значит строка, заведённая **новым** запуском сида, правилу
невидима: после любого нового прогона (новое демо-блюдо, восстановление стенда)
решение владельца «сделай у них нормальную связь с каноном» выполнялось бы
наполовину и **молча** — команда сообщала бы «связал N» и не знала бы о тех,
кого не увидела.

Из трёх возможных выходов (см. DRF-2429) выбран **отдельный шаг у сида**: сид
после записи делает ровно тот переход, который делала 0017, по своим же строкам.
Цена и смысл каждого варианта — в теле PR; здесь важно одно: **смысл статусов не
меняется**. ``unmapped`` по-прежнему значит «про строку ещё никто ничего не
сказал», ``review_required`` — «связь есть, провенанса нет, ждёт решения», и
переход между ними принадлежит правилу, а не тому, кто мимо него пишет.

# Почему модуль, а не копия в сиде

Копия правила в сиде разошлась бы с миграцией молча — а сравнивать их было бы
некому. Поэтому здесь единственная реализация, а ``_mapping_status_backfill``
(исторический дом, на который ссылается миграция) теперь к ней и обращается:
двух правил нет, есть одно и два вызывающих.

Функция намеренно ничего не импортирует из ``services.models``: миграция
передаёт ей **исторический** класс модели через ``apps.get_model``, и импорт
живой модели в этот путь означал бы, что старая миграция однажды выполнится
поверх новой схемы.
"""

from __future__ import annotations

from typing import Any

#: Значения статусов строками: этот модуль зовут и из миграции, где живой
#: ``SalonService.MappingStatus`` недоступен по построению.
UNMAPPED = "unmapped"
REVIEW_REQUIRED = "review_required"


def promote_linked_undecided(rows: Any) -> dict[str, int]:
    """Проставить ``review_required`` там, где связь есть, а решения ещё нет.

    ``rows`` — модель или готовый QuerySet ``SalonService``. QuerySet позволяет
    сузить переход до строк одного прогона сида: сид отвечает за свои строки и
    не берётся решать за чужие.

    Returns:
      ``{"promoted": n, "still_unmapped": m, "examined": k}`` — что переведено,
      что осталось без связи и **каков охват**. Охват здесь не украшение: ноль
      переводов честен и при пустой выборке (не та база, сид не накатан), и без
      охвата отчёт прочитался бы как «всё уже связано».

    Строки с принятым решением не трогаются: повторный прогон не сбрасывает
    подтверждённую связь обратно в очередь — иначе механизм, заведённый хранить
    человеческую работу, ею же и уничтожал бы.
    """

    queryset = rows.objects.all() if hasattr(rows, "objects") else rows
    examined = queryset.count()
    undecided = queryset.filter(mapping_status=UNMAPPED)
    promoted = undecided.filter(template__isnull=False).update(
        mapping_status=REVIEW_REQUIRED,
    )
    # Вторая ветвь не пишется: «связи нет» — это и есть умолчание ``unmapped``,
    # и переписать его в него же значило бы сделать вид, что решение принято.
    still_unmapped = queryset.filter(mapping_status=UNMAPPED).count()
    return {
        "promoted": promoted,
        "still_unmapped": still_unmapped,
        "examined": examined,
    }


__all__ = ["REVIEW_REQUIRED", "UNMAPPED", "promote_linked_undecided"]
