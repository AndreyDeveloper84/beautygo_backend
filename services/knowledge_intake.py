"""Правила ввода знания о процедурах — одни на все входы (DRF-2717).

Знание о процедурах (:class:`~services.models.ProcedureCapability`,
:class:`~services.models.CapabilityGoalLink`, DRF-2606) вносится двумя входами:
формой в Django-admin и засевом из файла (``seed_procedure_knowledge``). База
отклоняет неподтверждённое основание сама — ограничениями ``CHECK``. Но отказ
базы приходит именем ограничения и после того, как человек нажал «Сохранить»;
а два входа с двумя своими проверками однажды разойдутся.

Поэтому условия записаны здесь один раз, словами для человека и по полям, и
оба входа спрашивают их ДО записи. База остаётся последним рубежом, а не
единственным.

Импорт — не подтверждение
-------------------------
Читатель знания (:mod:`services.capabilities`) верит полю ``status``: что
``approved``, то и говорится человеку. Значит, вход обязан быть строже базы.
База требует у подтверждённой строки «кто ИЛИ какое правило» — и любая
непустая строка в ``confirmed_rule`` её устроит. Здесь — нет:

* подтвердить из файла можно только правилом из :data:`KNOWN_CONFIRMATION_RULES`,
  и сегодня этот набор **пуст**: правила, которым владелец разрешил бы
  подтверждать знание без человека, не существует. Из файла поэтому заводится
  только черновик, а подтверждает человек в админке;
* имя правила — константа в коде у того, кто правило применяет, а не строка
  из данных. Так же устроены ``seed_canonical_catalog.APPROVAL_RULE`` и
  ``confirm_seeded_links.SEED_LINK_RULE``. Новое правило добавляется сюда
  отдельной правкой со ссылкой на решение владельца;
* ссылка на источник не может быть пустой или заглушкой.

Чего эти проверки НЕ могут: отличить настоящий источник от выдуманного и
верное утверждение от неверного. Это остаётся за куратором и рецензентом.

Здесь только форма утверждения. Содержание — что процедура умеет и чем это
подтверждено — собирает владелец; кодом знание не выдумывается.
"""

from __future__ import annotations

import re

#: То же выражение, что в ``capabilitygoallink_course_not_a_bare_number``.
_BARE_NUMBER = re.compile(r"^\s*[0-9]+([.,][0-9]+)?\s*$")

#: Срок результата без единой буквы — то же выражение, что в ограничениях базы
#: (``services.models.TIMEFRAME_WITHOUT_WORDS``); равенство держит узел.
_WITHOUT_WORDS = re.compile(r"^[^A-Za-zА-Яа-яЁё]*$")

APPROVED = "approved"

#: Правила владельца, которыми знание может быть подтверждено БЕЗ человека.
#:
#: Пусто намеренно. Пока владелец не назвал такое правило, строка из файла
#: подтверждённой стать не может, каким бы ни было её ``confirmed_rule``.
KNOWN_CONFIRMATION_RULES: frozenset[str] = frozenset()

#: Слова, которые ссылкой на источник не являются. Список закрытый и короткий:
#: он ловит заглушку, а не оценивает источник.
_SOURCE_PLACEHOLDERS = frozenset({
    "нет", "источник", "ссылка", "ссылка на источник", "название документа",
    "документ", "тест", "пример",
    "n/a", "na", "none", "null", "todo", "tbd", "source", "ref", "reference",
    "link", "url", "test", "example", "xxx",
})

#: Меньше — не ссылка и не название, а пометка.
_SOURCE_MIN_SIGNS = 4


def source_ref_problem(source_ref: str) -> str | None:
    """Почему это не ссылка на источник; ``None`` — похоже на ссылку.

    Отличает заглушку от ссылки, и только. Проверить, что источник существует
    и говорит именно это, код не может.
    """
    text = (source_ref or "").strip()
    if not text:
        return "Укажите ссылку на источник или название документа."
    signs = re.sub(r"[\W_]+", "", text)
    if len(signs) < _SOURCE_MIN_SIGNS or text.casefold() in _SOURCE_PLACEHOLDERS:
        return (
            f"«{text}» не похоже на ссылку на источник: нужна ссылка или название "
            "документа, по которому утверждение можно перепроверить."
        )
    return None


def rule_problem(confirmed_rule: str, rule_version: str) -> str | None:
    """Почему этим правилом подтвердить нельзя; ``None`` — правило известно."""
    rule = (confirmed_rule or "").strip()
    if not rule:
        return (
            "Подтверждение из файла возможно только названным правилом владельца "
            "(confirmed_rule). Подтверждение человеком делается в админке."
        )
    if rule not in KNOWN_CONFIRMATION_RULES:
        known = ", ".join(sorted(KNOWN_CONFIRMATION_RULES)) or "набор пуст"
        return (
            f"Правило «{rule}» не входит в набор правил, которыми владелец разрешил "
            f"подтверждать знание без человека ({known}). Заведите строку черновиком "
            "и подтвердите её в админке."
        )
    if not (rule_version or "").strip():
        return "У правила должна быть версия (rule_version)."
    return None


def provenance_errors(*, status: str, source_ref: str, has_confirmer: bool) -> dict[str, str]:
    """Чего не хватает, чтобы строку можно было назвать подтверждённой.

    Строже ``<класс>_approved_requires_provenance``: тот же состав (источник и
    подтверждающий), но источник должен быть похож на источник. Кто может быть
    подтверждающим, решает вход: форма — человек, который сохраняет; засев —
    :func:`rule_problem`. Момент подтверждения вход ставит сам.

    Возвращает ``{поле: сообщение}``; пусто — можно сохранять.
    """
    if status != APPROVED:
        return {}
    errors: dict[str, str] = {}
    problem = source_ref_problem(source_ref)
    if problem:
        errors["source_ref"] = "Подтверждённое утверждение должно ссылаться на источник. " + problem
    if not has_confirmer:
        errors["status"] = (
            "Подтвердить может только человек или названное правило владельца — "
            "не указано ни то, ни другое."
        )
    return errors


def course_errors(
    *,
    course_pattern: str,
    variability_note: str,
    evidence_source: str,
    source_ref: str,
) -> dict[str, str]:
    """Что не так с описанием курса у связи возможности с целью.

    Зеркало двух ограничений базы: курс не хранится голым числом и не
    хранится без оговорки о разбросе и основания (решение владельца 29.09 —
    «обычно курс N» без оговорки и источника есть маркетинговое обещание).
    """
    pattern = (course_pattern or "").strip()
    if not pattern:
        return {}
    errors: dict[str, str] = {}
    if _BARE_NUMBER.match(pattern):
        errors["course_pattern"] = (
            "Курс описывается словами, а не одним числом: «10» нельзя, "
            "«обычно рассматривается как курс сеансов» — можно."
        )
    if not (variability_note or "").strip():
        errors["variability_note"] = (
            "У курса должна быть оговорка о разбросе: от чего зависит, у кого бывает иначе."
        )
    if not (evidence_source or "").strip():
        errors["evidence_source"] = "У курса должен быть источник: откуда это известно."
    problem = source_ref_problem(source_ref)
    if problem:
        errors["source_ref"] = "У курса должна быть ссылка на источник. " + problem
    return errors


def timeframe_errors(
    *,
    field: str,
    value: str,
    variability_note: str,
    evidence_source: str,
    source_ref: str,
) -> dict[str, str]:
    """Что не так со сроком результата — у возможности или у связи с целью.

    Решение владельца 02.10 (блок B): срок результата — «не самостоятельное
    число без контекста, источника и оговорки о вариативности»; защита та же,
    что у курса. ``field`` — имя поля со сроком: ``result_timeframe`` у
    возможности, ``result_horizon`` у связи.

    Входы спрашивают это у ЛЮБОЙ строки, в том числе у черновика, — как курс.
    База судит только подтверждённую строку
    (``<класс>_approved_*_grounded`` / ``*_in_words``): она последний рубеж и
    не должна ронять миграцию на черновике, заведённом раньше правила.

    «Словами» значит: в значении есть хотя бы одна буква. «3», «3–5», «~10 %»
    — отказ. Это строже, чем у курса, где ловится только одно число.

    Чего проверка НЕ ловит: срок числом со словом («3 недели», «через 5
    сеансов») при заполненных оговорке и источнике проходит. Отсутствие слов —
    форма, а не смысл; годится ли срок по смыслу, решает рецензент.
    """
    text = (value or "").strip()
    if not text:
        return {}
    errors: dict[str, str] = {}
    if _WITHOUT_WORDS.match(text):
        errors[field] = (
            "Срок результата описывается словами, а не числом: «3» и «3–5» нельзя, "
            "«обычно заметно в течение первых недель» — можно."
        )
    if not (variability_note or "").strip():
        errors["variability_note"] = (
            "У срока результата должна быть оговорка о разбросе: от чего зависит, "
            "у кого бывает иначе."
        )
    if not (evidence_source or "").strip():
        errors["evidence_source"] = "У срока результата должен быть источник: откуда это известно."
    problem = source_ref_problem(source_ref)
    if problem:
        errors["source_ref"] = "У срока результата должна быть ссылка на источник. " + problem
    return errors


