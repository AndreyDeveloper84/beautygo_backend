def test_duration_survives_normalization():
    """«(60 минут)» остаётся в ключе.

    Соблазн срезать длительность велик: §93 прямо говорит, что она не
    создаёт нового канона. Но отсюда не следует, что её можно выкинуть
    здесь. «Массаж спины (30 минут)» и «Массаж спины (60 минут)» —
    разные предложения салона, и решить, что оба ведут к одному канону,
    обязан человек, записав два синонима. Срезав скобку тут, мы бы
    приняли это решение за него и молча.
    """
    a = normalize_service_name("Массаж спины (30 минут)")
    b = normalize_service_name("Массаж спины (60 минут)")
    assert a != b
    assert "30" in a


def test_words_are_not_dropped():
    """«Массаж спины» и «Массаж» не схлопываются."""
    assert normalize_service_name("Массаж спины") != normalize_service_name("Массаж")


def test_cases_are_not_folded():
    """Падежи не приводятся: «подмышек» и «подмышки» остаются разными.

    Свести их — работа синонима, написанного человеком, а не
    стеммера. Стеммер сведёт заодно «бикини классическое» с «бикини
    тотальным», и мы получим связь, которой никто не подтверждал.
    """
    assert normalize_service_name("подмышек") != normalize_service_name("подмышки")
