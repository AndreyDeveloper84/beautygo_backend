"""Нормализация названия — таблица случаев как контракт.

Форма правила скопирована с той, что работает на связке зеркала
(`ai-bot-platform`, `apps/catalog/services/linking.py`). Общего кода
между репозиториями нет, и сторожа на расхождение нет тоже — вынести
модуль отсюда некуда. Значит две реализации могут разойтись молча, и
первым признаком станет не ошибка, а синоним, который перестал
находиться.

Таблица ниже — единственное, что делает расхождение видимым: если
правило здесь изменят, красным станет этот файл, а не поиск оператора
через месяц.

Вторая половина файла не менее важна первой: она закрепляет, чего
нормализация **не делает**. Соблазн «заодно отбросить длительность» или
«привести падежи» возникает при первом же взгляде на список пилота — и
каждый такой шаг превращает поиск в догадку, а догадка про смысл здесь
запрещена (§73).
"""
from __future__ import annotations

import pytest

from services.normalization import normalize_service_name

# (вход, ожидаемый ключ, почему это правило существует)
CASES = [
    ("Подмышки", "подмышки", "регистр не различает услуги"),
    ("ПОДМЫШКИ", "подмышки", "регистр не различает услуги"),
    ("  Подмышки  ", "подмышки", "оператор копирует строки с пробелами"),
    ("Бикини   глубокое", "бикини глубокое", "двойные пробелы из выгрузок"),
    ("Бёдра полностью", "бедра полностью", "ё и е пишут вперемешку"),
    ("бедра ПОЛНОСТЬЮ", "бедра полностью", "то же слово, другой ввод"),
    ('Комплекс «все тело»', "комплекс все тело", "каталог пишет в ёлочках, салон — без"),
    ('Комплекс "все тело"', "комплекс все тело", "и в прямых кавычках тоже"),
    ("", "", "пустое остаётся пустым, а не превращается в что-то"),
    (None, "", "отсутствие не подставляет умолчание"),
]


@pytest.mark.parametrize("raw,expected,why", CASES, ids=[c[2] for c in CASES])
def test_normalization_contract(raw, expected, why):
    assert normalize_service_name(raw) == expected, why


def test_normalization_is_idempotent():
    """Ключ от ключа — тот же ключ.

    Иначе повторное сохранение строки меняло бы её ключ, и уникальность
    по нормализованному тексту стала бы зависеть от числа сохранений.
    """
    for raw, _, _ in CASES:
        once = normalize_service_name(raw)
        assert normalize_service_name(once) == once


