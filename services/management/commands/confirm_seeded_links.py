"""``manage.py confirm_seeded_links [--apply] [--tenant <slug>]`` — довести связь
строк сида (DRF-2408).

Решение владельца §77 п.31 (24.09): демонстрационные салоны остаются, и у их
услуг должна быть **нормальная связь с каноном**. Привязка у них уже стоит —
не хватает **статуса и провенанса**.

Что команда берёт
-----------------

Строку, у которой **всё** из перечисленного:

* источник ``seed``;
* основание пусто (``mapping_source_ref == ""``);
* привязка к канону есть (``template`` не пуст);
* статус ``review_required``;
* салон не в ``PROTECTED_SLUGS``.

Отбор **положительный**: названо, что берём, а не что пропускаем. Отрицательный
однажды прихватил бы группу, о которой мы ещё не знаем, — так уже было с
неизмеренными салонами ``mkt-*``.

**Почему пустое основание — часть отбора, а не предположение.** У строк сида оно
пусто, и на этом стоит всё различение (см. ниже). Но ``source=seed`` пишет не
только сид демонстрационных салонов: так же помечают строки
``bootstrap_tech_tenant`` (салон ``tech-probe``) и ``bootstrap_e2e_wave1``.
Сегодня ни одна их строка под отбор не попадает, но это совпадение, а не
свойство. Проверять основание — дешевле, чем однажды проштамповать
«демонстрационный набор» на строке технического стенда. Заодно это не даёт
затереть чужое основание, если оно у строки уже есть.

Почему своё имя правила, а не правило выбора мастера
-----------------------------------------------------

Строки выбора мастера узнаются по ``mapping_source_ref`` вида ``master_select:*``
(DRF-2406), а у строк сида основание пусто. Подтвердить их тем правилом значило
бы написать «мастер выбрал» там, где мастер не выбирал, — подлог провенанса.
Провенанс потом читают как факт, поэтому такая ошибка дороже незакрытой очереди.

Имя правила называет **происхождение**, а не заслугу: связь пришла из набора
демонстрационных салонов. «Проверено» было бы неправдой — никто ничего не
проверял.

Что команда считает, но не трогает
-----------------------------------

Своё же правило «исключение должно быть **названо числом**» применяется ко всем
трём посылкам, на которых стоит работа, а не к одной.

**Что доказывает ноль.** Ноль исключений честен только при **непустом охвате**:
при пустой выборке — не тот салон, не та база, сид не накатан — все три числа
тоже нули, и отчёт прочитается как «исключений нет». Поэтому первым печатается
охват, а при нулевом охвате сказано прямо, что нули ниже ничего не доказывают.

Три посылки:

* **без привязки** — подтверждать нечего, и схема такую строку не примет;
* **статус не ``review_required``** — строки сида заводятся со статусом
  ``unmapped`` (сид его не ставит вовсе), а нынешние ``review_required``
  появились разовым прогоном 0017 08.09. Значит **новая** строка сида этой
  команде невидима. Переводить ``unmapped`` она не вправе: это «про строку ещё
  никто ничего не сказал», и переход принадлежит 0017;
* **с заполненным «кто»** — наполовину заполненное состояние, до которого
  доводит очередь: администратор вписал автора и не сменил статус. Такой строке
  провенанс правила ставится, а человек снимается — иначе схема запретит «и
  человек, и правило» и прогон упадёт на середине. Человек при этом **теряется**,
  поэтому число таких строк печатается: молча — нельзя.

Чего команда НЕ делает
----------------------

* **Ничего не создаёт и не удаляет строк.** Только статус и провенанс.
* **Не трогает защищённые слаги.** ``formula-tela`` несёт настоящие записи
  настоящих людей.
* **Не ходит в ворота резолвера.** ``authorize_apply`` охраняет запись решений
  резолвера (MAP-AUTO-06): выбор кандидата, план провенанса, правила R0/R1/R2.
  Здесь кандидата не ищут — привязка уже стоит. Проверено запуском, а не
  рассуждением: узел ``test_the_resolver_gate_is_not_in_the_way`` ставит рядом
  отказ ворот на ``map_salon_services --apply`` и запись этой командой.
* **Не оставляет синонима.** Админка на переводе в ``VERIFIED`` записывает
  название салона подтверждённым синонимом (§93, шаг 4); запись через
  ``update()`` мимо админки этого не делает. Размен назван в докстроке админки;
  здесь он повторяется на объёме, и следующий читатель должен знать.

Сухой прогон — умолчание
------------------------

Без ``--apply`` команда печатает область, время снятия и числа, не записывая
ничего. Прямой ``UPDATE`` в обход команды оставил бы провенанс пустым или
выдуманным — то есть записал бы «подтверждено» без подтвердившего.
"""

from __future__ import annotations

from django.core.management.base import BaseCommand, CommandError
from django.db.models import Count
from django.utils import timezone

#: Имя правила: называет ПРОИСХОЖДЕНИЕ связи, а не заслугу.
SEED_LINK_RULE = "seeded_demo_catalog_link"
#: Версия правила. Меняется, когда меняется само основание подтверждения.
SEED_LINK_RULE_VERSION = "1"
#: Основание — имя команды, которой строки заведены. Издание набора (файл сида)
#: сюда НЕ пишется: команда его не знает, потому что `seed_demo_salons`
#: принимает `--file`, и записать умолчание значило бы назвать основанием файл,
#: которого, возможно, не было. Лучше меньше, чем неправда.
SEED_LINK_SOURCE_REF = "seed_demo_salons"

#: Слаги, в которые команда не пишет никогда. Берутся у сида демонстрационных
#: салонов, а не повторяются здесь: две копии одного списка расходятся молча, и
#: добавивший слаг в одном месте не узнает, что второе продолжает писать.
try:  # pragma: no cover - импорт команды из команды, подстраховка на случай переноса
    from services.management.commands.seed_demo_salons import PROTECTED_SLUGS
except ImportError:  # pragma: no cover
    PROTECTED_SLUGS = frozenset({"formula-tela"})


class Command(BaseCommand):
    help = (
        "Довести связь строк сида: VERIFIED со своим правилом и провенансом. "
        "По умолчанию — сухой прогон; запись только с --apply."
    )

    def add_arguments(self, parser) -> None:
        parser.add_argument(
            "--apply", action="store_true",
            help="записать (по умолчанию — только показать, что было бы сделано)",
        )
        parser.add_argument(
            "--tenant", default="",
            help="сузить до одного салона по слагу (по умолчанию — все, кроме защищённых)",
        )

    def handle(self, *args, **options) -> None:
        from django.conf import settings
        from django.db import connection

        from services.models import SalonService
        from tenants.models import Tenant

        slug = options["tenant"].strip()
        if slug in PROTECTED_SLUGS:
            raise CommandError(
                f"салон «{slug}» защищён: он несёт настоящие записи настоящих людей, "
                "и правило про демонстрационный набор к нему не применяется"
            )
        if slug and not Tenant.objects.filter(slug=slug).exists():
            # Молчаливый ноль неотличим от «нечего делать»: та же ошибка, что
            # опечатка в срезе сухого прогона резолвера (DRF-2407).
            raise CommandError(f"салона со слагом «{slug}» нет")

        seeded = SalonService.objects.filter(
            source=SalonService.Source.SEED,
            mapping_source_ref="",
        ).exclude(tenant__slug__in=PROTECTED_SLUGS)
        if slug:
            seeded = seeded.filter(tenant__slug=slug)

        queued = seeded.filter(mapping_status=SalonService.MappingStatus.REVIEW_REQUIRED)
        linked = queued.filter(template__isnull=False)

        # Три посылки, на которых стоит работа. Каждая считается и печатается:
        # если на стенде окажется исключение, оно должно быть НАЗВАНО.
        unlinked = queued.filter(template__isnull=True).count()
        not_queued = (
            seeded.filter(template__isnull=False)
            .exclude(mapping_status=SalonService.MappingStatus.REVIEW_REQUIRED)
            .exclude(mapping_status=SalonService.MappingStatus.VERIFIED)
            .count()
        )
        loses_a_human = linked.filter(mapping_confirmed_by__isnull=False).count()
        # Охват: сколько строк вообще попало под область. Без него нули выше
        # неотличимы от «выборка пуста».
        examined = seeded.count()

        by_tenant = dict(
            linked.values_list("tenant__slug").order_by().annotate(n=Count("id"))
        )
        total = sum(by_tenant.values())
        stamped_at = timezone.now()

        db = settings.DATABASES["default"]
        w = self.stdout.write
        w(f"предмет: база {db.get('NAME')}@{db.get('HOST') or 'local'} · "
          f"vendor {connection.vendor}")
        w(f"снято:   {stamped_at.isoformat(timespec='seconds')}")
        w(f"область: источник seed · основание пусто · статус review_required · "
          f"салон {slug or 'все, кроме защищённых'}")
        w(f"режим:   {'ЗАПИСЬ (--apply)' if options['apply'] else 'сухой прогон, записи нет'}")
        w(f"правило: {SEED_LINK_RULE} v{SEED_LINK_RULE_VERSION}")
        w("")

        for tenant_slug in sorted(by_tenant):
            w(f"  {tenant_slug:<20} {by_tenant[tenant_slug]:>4}")
        w("")
        # Охват — ПЕРВЫМ числом. Ноль исключений ниже честен только при
        # непустом охвате: при пустой выборке все три числа тоже нули, и отчёт
        # прочитается как «исключений нет».
        w(f"охват (строк сида просмотрено): {examined}")
        if examined == 0:
            w("ВНИМАНИЕ: охват пуст — нули ниже ничего не доказывают. "
              "Проверьте базу, слаг салона и что сид вообще накатан.")
        w(f"с привязкой (к записи):        {total}")
        w(f"без привязки (пропущено):      {unlinked}")
        w(f"не в очереди (пропущено):      {not_queued}")
        w(f"снимется «кто» с строк:        {loses_a_human}")

        if not options["apply"]:
            w("")
            w("сухой прогон: ничего не записано. Запись — тем же вызовом с --apply.")
            return

        written = linked.update(
            mapping_status=SalonService.MappingStatus.VERIFIED,
            mapping_confirmed_rule=SEED_LINK_RULE,
            mapping_rule_version=SEED_LINK_RULE_VERSION,
            mapping_confirmed_at=stamped_at,
            mapping_source_ref=SEED_LINK_SOURCE_REF,
            # Подтверждает правило: человек снимается. Оба заполненных поля
            # схема запрещает, и наполовину заполненная строка уронила бы
            # прогон на середине.
            mapping_confirmed_by=None,
        )
        w("")
        w(f"записано: {written}")
