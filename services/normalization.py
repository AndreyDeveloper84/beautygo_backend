"""Нормализация названия услуги — ключ поиска, а не отображение.

Форма нормализации взята **не из головы**: она повторяет ту, что уже
работает на связке зеркала (`ai-bot-platform`,
`apps/catalog/services/linking.py`, докстринг модуля):

    normalization is bot-side: lower (casefold), trim/collapse
    whitespace, ё→е, strip «ёлочки»

**Две реализации, общего кода нет, сторожа на расхождение нет.** Это
осознанный долг, а не недосмотр: репозитории разные, и вынести общий
модуль отсюда нельзя. Пока их две, они могут разойтись молча — и первым
признаком будет не ошибка, а синоним, который перестал находиться.
Поэтому таблица случаев ниже продублирована тестом: если правило здесь
изменят, красным станет он, а не поведение поиска через месяц.

Что нормализация НЕ делает и делать не должна::

    не отбрасывает слова         «массаж спины» и «массаж» — разные услуги
    не приводит падежи           «подмышек» и «подмышки» останутся разными,
                                 и это правильно: сводить их — задача
                                 синонима, который написал человек, а не
                                 догадки алгоритма
    не удаляет цифры и скобки    «(60 минут)» — часть названия салона, и
                                 решение, что длительность не создаёт
                                 нового канона (§93), принимает человек

Иначе говоря: нормализация снимает **типографику**, а не смысл. Всё,
что про смысл, — работа человека, записанная синонимом с провенансом.
"""
from __future__ import annotations

import re

__all__ = ["normalize_service_name"]

#: Кавычки-ёлочки и их спутники. Снимаются, потому что каталог владельца
#: пишет «Комплекс "все тело"», а салон — Комплекс все тело.
_QUOTES = '«»""„“”\'‘’'

_WHITESPACE = re.compile(r"\s+")


def normalize_service_name(raw: str | None) -> str:
    """Ключ сравнения названий. Пустой вход даёт пустую строку.

    Пустая строка возвращается **как есть**, а не как `None` и не как
    ошибка: вызывающий сам решает, что значит отсутствие названия.
    Подставить сюда что-то осмысленное значило бы решить за него.
    """
    if not raw:
        return ""
    text = str(raw).casefold().replace("ё", "е")
    text = "".join(ch for ch in text if ch not in _QUOTES)
    return _WHITESPACE.sub(" ", text).strip()
