"""Вернуть в черновик подтверждённое без типа и проверки — общее для миграции и теста.

Модуль лежит в пакете миграций намеренно, как ``_drf2726_timeframe_demote``:
логика принадлежит миграции ``0035``, имя на ``_`` загрузчик Django
миграцией не считает.

Зачем шаг нужен
---------------
``0035`` добавляет ограничения: подтверждённая строка обязана иметь тип
утверждения, а если тип требует рецензента — и отметку проверки. Колонки
типа и проверки появляются этой же миграцией, тип — со значением
``unclassified``. Значит, **любая** строка, подтверждённая до неё, новое
ограничение нарушает. ``ADD CONSTRAINT`` проверяет лежащие строки, ``migrate``
на стенде идёт под ``set -e``.

Что шаг делает
--------------
Каждой подтверждённой строке ставит ``status = system_inference``. Больше
ничего: содержание, источник и след подтверждения (``confirmed_by``,
``confirmed_at``) сохраняются. Тип миграция не угадывает и проверку не
выдумывает: какого типа утверждение, решает куратор; проверено ли оно —
рецензент.

Это шире двух прежних шагов (``0032``, ``0033``): там возвращались строки с
одним названным изъяном, здесь — всё подтверждённое. Иначе нельзя: у
подтверждённой строки без типа нет способа узнать, нужен ли ей рецензент.

Чего шаг не делает
------------------
* Черновики не трогает.
* Обратного действия нет.

Сколько строк затронуто, шаг печатает числом — без содержимого.
"""
from __future__ import annotations


def demote(capability_model, link_model) -> dict[str, int]:
    """Вернуть все подтверждённые строки в черновик; вернуть их число."""
    return {
        "capabilities": capability_model.objects.filter(status="approved").update(
            status="system_inference",
        ),
        "goal_links": link_model.objects.filter(status="approved").update(
            status="system_inference",
        ),
    }
