"""Классификация существующих связей — общая для миграции и для теста.

Модуль лежит в пакете миграций намеренно: логика принадлежит именно
миграции. Имя начинается с подчёркивания, поэтому загрузчик Django его
не подхватывает как миграцию (`MigrationLoader` пропускает имена на
``_`` и ``~``), а тест может позвать её напрямую.

Причина выносить: миграцию нельзя вызвать из теста, не поднимая всю
машину `MigrationExecutor`, — и на практике это означает, что правило,
проставившее статус двумстам строкам боевого пилота, остаётся вообще
непроверенным. Здесь проверяется само правило, а миграция — три строки
поверх него.
"""
from __future__ import annotations


def classify(salon_service_model) -> dict[str, int]:
    """Проставить статус связи там, где решения ещё не принимали.

    Правило владельца (`OPEN_DECISIONS.md` §76) целиком:

    * связь есть, доказуемого provenance нет → ``REVIEW_REQUIRED``;
    * связи нет либо ссылка повреждена → ``UNMAPPED``;
    * ``VERIFIED`` — **никому**, ни одной строке.

    Третий пункт исполняется тем, что этот код не умеет писать
    ``VERIFIED`` вовсе. Это не осторожность: схема требует provenance
    (``salonservice_verified_requires_provenance``), а у миграции его нет
    и взяться ему неоткуда — она не человек и не правило о каталоге.

    **Что на пилоте окажется по ту и другую сторону** (замер 08.09,
    у него срок годности — перемерять, а не цитировать):

    ==================== ===== ===============================================
    206 связей с шаблоном seed  все до одной поставлены `seed_demo_salons`
    58 услуг без шаблона  ycl.  единственный салон с настоящей интеграцией
    ==================== ===== ===============================================

    То есть ``REVIEW_REQUIRED`` получат демонстрационные связи, а
    настоящий каталог живого салона уйдёт в ``UNMAPPED`` целиком.
    Это честно в обоих случаях, но читать это надо именно так: не
    «206 связей ждут проверки», а «проверять предстоит 58 услуг,
    которых пока не связал никто».

    Строки с уже принятым решением не трогаются. Иначе повторный прогон
    сбросил бы подтверждённую связь обратно в ``REVIEW_REQUIRED`` — то
    есть уничтожил бы человеческую работу тем самым механизмом, который
    заведён её сохранять.
    """
    # DRF-2429: само правило переехало в ``services.mapping_status`` — у него
    # появился второй вызывающий (шаг сида), и две копии одного перехода
    # разошлись бы молча. Здесь остался исторический дом: миграция ссылается
    # на этот модуль, поведение не изменилось, реализация одна.
    from services.mapping_status import promote_linked_undecided

    counts = promote_linked_undecided(salon_service_model)
    return {
        "review_required": counts["promoted"],
        "unmapped": counts["still_unmapped"],
    }
