"""Вернуть в черновик подтверждённое без вида доказательства — общее для миграции и теста.

Модуль лежит в пакете миграций намеренно, как ``_drf2726_timeframe_demote``:
логика принадлежит миграции ``0036``, имя на ``_`` загрузчик Django
миграцией не считает.

Зачем шаг нужен
---------------
``0036`` добавляет ограничение: у ПОДТВЕРЖДЁННОЙ строки вид доказательства
(``evidence_kind``) — один из закрытого списка (решение владельца №4 от 02.10).
До этой миграции поле было свободным текстом и необязательным, так что
подтверждённая строка с пустым или произвольным видом возможна.
``ADD CONSTRAINT`` проверяет лежащие строки, ``migrate`` на стенде идёт под
``set -e``, и прочитать стенд, чтобы узнать, есть ли такие строки, нечем.

Что шаг делает
--------------
Подтверждённой строке, у которой вид доказательства пуст или не из списка,
ставит ``status = system_inference``. Больше ничего: содержание, сам текст
вида и след подтверждения (``confirmed_by``, ``confirmed_at``) сохраняются.
Вид из свободного текста миграция не угадывает: «протокол салона» — это
консенсус специалистов, инструкция производителя или маркетинг, решает
куратор.

Чего шаг не делает
------------------
* Черновики не трогает — база их не судит.
* Обратного действия нет.

Сколько строк затронуто, шаг печатает числом — без содержимого.
"""
from __future__ import annotations

#: Копия ``ClaimEvidence.EvidenceKind`` на момент миграции: миграция не должна
#: менять поведение вслед за будущей правкой списка.
KNOWN_KINDS = (
    "clinical_guideline",
    "systematic_review",
    "rct",
    "manufacturer_ifu",
    "regulatory_document",
    "professional_consensus",
    "legal_rule",
    "product_policy",
)


def _offenders(model):
    """Подтверждённые строки, которые новое ограничение не пропустило бы."""
    return model.objects.filter(status="approved").exclude(evidence_kind__in=KNOWN_KINDS)


def demote(capability_model, link_model) -> dict[str, int]:
    """Вернуть нарушающие подтверждённые строки в черновик; вернуть их число."""
    return {
        "capabilities": _offenders(capability_model).update(status="system_inference"),
        "goal_links": _offenders(link_model).update(status="system_inference"),
    }
