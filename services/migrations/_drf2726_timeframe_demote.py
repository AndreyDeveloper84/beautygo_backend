"""Вернуть в черновик подтверждённый срок без основания — общее для миграции и теста.

Модуль лежит в пакете миграций намеренно, как ``_mapping_status_backfill``:
логика принадлежит миграции ``0032``, имя на ``_`` загрузчик Django
миграцией не считает.

Зачем шаг нужен
---------------
``0032`` добавляет ограничения: у ПОДТВЕРЖДЁННОЙ строки срок результата
(``result_timeframe`` у возможности, ``result_horizon`` у связи с целью) —
только словами и только с оговоркой о разбросе, источником и ссылкой.
``ADD CONSTRAINT`` проверяет уже лежащие строки, а ``migrate`` на стенде идёт
под ``set -e``: одна нарушающая строка остановила бы запуск сайта.

Такая строка возможна. Форма админки появилась 02.10 (DRF-2717), поля
оговорки у возможности тогда не было вовсе — любая возможность, подтверждённая
со сроком, новое правило нарушает. Прочитать стенд, чтобы узнать, есть ли
такие строки, нечем.

Что шаг делает
--------------
Нарушающей подтверждённой строке ставит ``status = system_inference``. Больше
ничего: ни текст, ни срок, ни источник не трогаются. По решению владельца
02.10 (блок B) такой срок и не должен был считаться подтверждённым; черновик
человеку не говорится, а вернуть подтверждение можно в админке, вписав
оговорку.

``confirmed_by`` и ``confirmed_at`` **сохраняются**: это единственный след
того, кто и когда строку подтверждал, и единственный знак куратору, что её
вернула в черновик миграция, а не он сам. Отметку снимет первое же сохранение
в админке (``_ClaimAdmin.save_model``).

Чего шаг не делает
------------------
* Черновики не трогает — база их не судит.
* Подтверждённые строки без срока или с обоснованным сроком не трогает.
* Обратного действия нет: откат, вновь «подтверждающий» эти строки, выдал бы
  решение миграции за решение человека.

Сколько строк затронуто, шаг печатает числом — без содержимого.
"""
from __future__ import annotations

from django.db.models import Q

#: Копия ``services.models.TIMEFRAME_WITHOUT_WORDS`` на момент миграции:
#: миграция не должна менять поведение вслед за будущей правкой модели.
WITHOUT_WORDS = r"^[^A-Za-zА-Яа-яЁё]*$"


def _offenders(model, field: str):
    """Подтверждённые строки, которые новые ограничения не пропустили бы."""
    return (
        model.objects.filter(status="approved")
        .exclude(**{field: ""})
        .filter(
            Q(variability_note="")
            | Q(evidence_source="")
            | Q(source_ref="")
            | Q(**{f"{field}__regex": WITHOUT_WORDS})
        )
    )


def demote(capability_model, link_model) -> dict[str, int]:
    """Вернуть нарушающие подтверждённые строки в черновик; вернуть их число."""
    return {
        "capabilities": _offenders(capability_model, "result_timeframe").update(
            status="system_inference",
        ),
        "goal_links": _offenders(link_model, "result_horizon").update(
            status="system_inference",
        ),
    }
