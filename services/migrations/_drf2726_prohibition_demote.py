"""Вернуть в черновик подтверждённый запрет без предмета — общее для миграции и теста.

Модуль лежит в пакете миграций намеренно, как ``_drf2726_timeframe_demote``:
логика принадлежит миграции ``0033``, имя на ``_`` загрузчик Django
миграцией не считает.

Зачем шаг нужен
---------------
``0033`` добавляет ограничение: у ПОДТВЕРЖДЁННОГО запрещённого утверждения
(``claim_scope = prohibited_claim``) должен быть предмет запрета
(``prohibited_statement``). Колонка появляется этой же миграцией — значит,
любой запрет, подтверждённый до неё, ограничение нарушает: вписать предмет
было некуда. ``ADD CONSTRAINT`` проверяет лежащие строки, ``migrate`` на
стенде идёт под ``set -e``, и прочитать стенд, чтобы узнать, есть ли такие
строки, нечем.

Что шаг делает
--------------
Подтверждённому запрету без предмета ставит ``status = system_inference``.
Больше ничего: ни ключ, ни ограничения, ни источник не трогаются, след
подтверждения (``confirmed_by``, ``confirmed_at``) сохраняется — по той же
причине, что в ``_drf2726_timeframe_demote``.

Почему это не ослабляет защиту
------------------------------
Клиентский путь знания — разрешительный: наружу выходит только подтверждённое
и поддержанное (:func:`services.capabilities.client_facing_capabilities`), а
запрещённое не отдаётся в любом статусе. Запрет без предмета проверяющему
исполнить нечем — он держался на прозе в ``limitations``. Возврат в черновик
ничего не разрешает; он показывает куратору, что запрет надо сформулировать.

Чего шаг не делает
------------------
* Предмет из ``limitations`` не выводит: формулировку запрета пишет человек.
* Черновики и подтверждённые строки других ``claim_scope`` не трогает.
* Обратного действия нет.

Сколько строк затронуто, шаг печатает числом — без содержимого.
"""
from __future__ import annotations


def _offenders(model):
    """Подтверждённые запреты, которые новое ограничение не пропустило бы."""
    return model.objects.filter(
        status="approved", claim_scope="prohibited_claim", prohibited_statement="",
    )


def demote(capability_model, link_model) -> dict[str, int]:
    """Вернуть подтверждённые запреты без предмета в черновик; вернуть их число."""
    return {
        "capabilities": _offenders(capability_model).update(status="system_inference"),
        "goal_links": _offenders(link_model).update(status="system_inference"),
    }
