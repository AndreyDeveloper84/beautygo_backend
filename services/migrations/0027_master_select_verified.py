"""Разовый прогон правила по уже существующим строкам выбора мастера (DRF-2406).

Решение владельца §77 п.30 (24.09): выбор мастера из канона — достаточное
основание, связь подтверждается **правилом**. Живой путь закрыт в
``services/offer_selection.py``; здесь закрываются строки, выбранные **до**
этой правки.

Признак отбора назван явно и узко: ``mapping_source_ref`` начинается с
``master_select:``, статус ``review_required``, привязка к канону есть.

**Почему отбор положительный, а не «все, кроме известных чужих».** На стенде
24.09 строк в очереди 212: шесть — выбор мастера, остальные — нет. Подтвердить
чужую строку этим правилом значило бы написать «мастер выбрал» там, где мастер
не выбирал, — подлог провенанса; его потом читают как факт, поэтому ошибка хуже
незакрытой очереди.

И отрицательный отбор такую ошибку однажды сделает. Тот же замер показал
группу, которой никто не ждал: 206 строк «сида» — это **не** 171 строка
генератора демо; ещё 35 лежат в салонах ``mkt-*``, созданных 23.08, и чем они
заведены — **не измерено**. Правило «всё, кроме демо» подтвердило бы их молча.
Поэтому здесь названо, что берём, а не что пропускаем: у чужой строки основание
чужое, каким бы оно ни было — пустым, как у сида, или незнакомым.

Строки сида закрываются **своим** правилом со своей версией — DRF-2408.

**Почему привязка обязательна.** ``VERIFIED`` без шаблона запрещён схемой
(``salonservice_verified_requires_template``): подтверждать нечего, если связи
нет. Строка без привязки правилом не подтверждается — это узел листа, а не
следствие реализации.

**Выключенные строки берутся тоже, и это намеренно.** Мастер, убравший услугу
при живой записи, оставляет строку выключенной; выбор при этом **был**, и
провенанс о нём правду говорит. А если исключить такие строки, то при повторном
выборе они вернутся включёнными и навсегда останутся в очереди: живой путь
включает строку обратно, но провенанс не переписывает. В подбор выключенная
строка всё равно не попадает (``sellable_offer_q`` требует активной строки).
"""

