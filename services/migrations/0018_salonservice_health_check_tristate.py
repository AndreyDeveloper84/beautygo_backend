"""Признак здоровья салонной услуги становится трёхзначным.

    NULL   салон на вопрос НЕ ОТВЕЧАЛ
    True   салон говорит: скрининг нужен
    False  салон говорит: скрининг НЕ нужен

### Почему бэкфилл переводит ВСЕ существующие значения в NULL

Не «обнуляем на всякий случай». На момент этой миграции в колонке стоит
``False`` у всех строк (265 из 265, замер боевого пилота 09.09.2026) — и ни
одно из них не является ответом салона, **потому что интерфейса сказать
«нет» никогда не существовало**. Поле было ``BooleanField(default=False)``,
и ``False`` в нём означало ровно одно: строку создали. Салон об этой услуге
не спрашивали ни разу.

Перенести такие значения как «салон ответил: не нужно» значило бы выдать
умолчание колонки за решение человека — тот самый дефект, ради устранения
которого поле и становится трёхзначным. Поэтому честный перенос один: всё,
что есть сегодня, — это «не отвечали».

``True`` в колонке на момент замера нет ни одной (0 из 265), поэтому вопрос
«что делать с поднятыми вручную» здесь не стоит. Условие ниже всё равно
трогает только ``False`` — чтобы миграция осталась верной, если такие
строки появятся между написанием и применением.

### Обратимость — названа, потому что она НЕ полная

Откат схемы вернёт колонку в ``NOT NULL``, и обратный перенос обязан чем-то
заполнить ``NULL``. Заполняет ``False`` — другого значения у двузначного
поля нет.

**Различие «салон не отвечал» против «салон сказал: не нужно» при откате
исчезает безвозвратно.** Оба станут ``False``, и разделить их потом будет
нечем: следа, отличающего одно от другого, в двузначной колонке не
остаётся.

Это надо знать ДО выкладки, а не после. Практически: откатывать миграцию
безопасно, пока никто не проставил ни одного осознанного ответа. После
первой же простановки откат уничтожает работу человека, и делает это молча.
"""

