"""Прямой ответ человека доезжает до памяти ИИ (DRF-2310, §77 п. 3).

# Зачем

``UserPersonalContext`` — это то, что ИИ ЗНАЕТ о человеке: подсказка в
промпт (``ai/personal_context_hint``) собирается из него, и происхождение
каждого поля лежит рядом в ``data_sources`` (``explicit`` / ``behavioral`` /
``conversational`` / ``transactional``).

Ответ на прямой вопрос анкеты живёт в другом месте — в профиле своего
домена. И вот что из этого следовало до этого модуля: человек прямо
говорит «я веган», а подсказка модели продолжает называть прежнюю диету,
выведенную из разговора месяц назад. Один предмет, два хранилища, два
разных ответа — и человек видит оба (выгрузка ст. 14 собирается по обоим
путям: ``users/personal_data_api`` отдаёт контекст, ``remembered_export`` —
профиль).

Поэтому прямой ответ пишется и сюда, с источником ``explicit``: **прямой
ответ главнее выведенного** (решение 24.09.2026). Пометка источника — не
украшение: без неё выведенное и названное неотличимы, и «главнее» нечем
исполнить.

# Чего этот модуль НЕ делает

* **Не пишет по любому касанию профиля.** Только когда человек назвал
  ответ. Прикосновение к профилю по другому поводу памяти не касается.
* **Не сводит столбцы.** Это два разных факта о происхождении
  («сказал в разговоре» против «ответил на вопрос»), и сведение их в одну
  колонку было бы миграцией данных живых людей без нужды.
* **Не стирает.** Стирание обоих путей уже держат ``forget_all_catalog`` и
  исполнитель удаления аккаунта — они убирают строку контекста целиком.
"""
from __future__ import annotations

from typing import Any

from users.models import UserPersonalContext

#: Происхождение прямого ответа. Значение из ``_SOURCE_CHOICES`` внутренней
#: ручки контекста — не своё слово, чтобы словари происхождения не разошлись.
EXPLICIT = "explicit"


def record_direct_answer(user: Any, field: str, value: str) -> None:
    """Записать в память ИИ то, что человек назвал сам.

    Строка контекста заводится, если её нет: отсутствие памяти — не причина
    потерять ответ. Пишутся ровно два поля — само значение и происхождение,
    — чтобы не затирать остальное содержимое строки.

    Повтор того же ответа с тем же происхождением не пишет ничего: у строки
    ``auto_now``-отметка, и лишняя запись двигала бы её без события.
    """
    context, _ = UserPersonalContext.objects.get_or_create(user=user)
    sources = dict(context.data_sources or {})
    if getattr(context, field) == value and sources.get(field) == EXPLICIT:
        return

    setattr(context, field, value)
    sources[field] = EXPLICIT
    context.data_sources = sources
    context.save(update_fields=[field, "data_sources", "updated_at"])
