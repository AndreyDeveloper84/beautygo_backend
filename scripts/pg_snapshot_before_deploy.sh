#!/bin/bash
# Снимок базы каталога ПЕРЕД тем, как что-либо тронет схему — DRF-1664, B-5 (5.1).
#
# Зовётся с хоста, из корня дерева выкладки, тем пользователем, который
# выкладывает (на пилоте — владелец дерева, taximeter). Зовут двое:
#   * deploy.sh — до `docker compose build && up -d`: entrypoint web-контейнера
#     сам делает `migrate` при старте, так что схему меняет именно `up -d`;
#   * .github/workflows/smoke-on-dev.yml — до явного `migrate`.
# Порядок несущий: откатывать нужно то состояние, которое было ДО схемных
# правок, а не после.
#
# Форма повторяет снимок бота (ai-bot-platform, deploy-dev.yml, #1510), с
# поправкой на актора: здесь входит НЕ root, поэтому `sudo -u` не нужен, а
# перенаправление `>` пишет файл тем же пользователем, что и всё остальное.
# Но процесс ВНУТРИ контейнера всё равно идёт от uid образа (в postgres:16-alpine
# USER не задан → root), и `--user` на exec нужен ровно так же, как у бота:
# кто позвал клиента docker и кто работает внутри контейнера — разные субъекты.
# Измерено 11.09.2026 на том же образе: pg_dump от uid 1000:1000 ходит по
# локальному сокету (drwxrwsr-t, pg_hba `local all all trust`), rc=0.
set -euo pipefail

# Снимок НЕ в дереве выкладки. Файл, написанный внутрь репозитория, ломает
# следующую выкладку: `git reset --hard` его снесёт (не бэкап), а неотслеживаемый
# растёт без ротации. Дом выкладывающего — сосед дерева, но «сосед» проверяется,
# не предполагается.
TREE="$(pwd -P)"
OWNER_UID="$(stat -c %u "$TREE")"
OWNER_GID="$(stat -c %g "$TREE")"
BACKUP_DIR="${PG_SNAPSHOT_DIR:-$HOME/beautygo-dev-backups}"
case "$BACKUP_DIR/" in
  "$TREE"/*)
    echo "::error::каталог снимков $BACKUP_DIR лежит внутри дерева выкладки $TREE — следующее обновление дерева его снесёт" >&2
    exit 1 ;;
esac

# Глубина — посчитанное число, не умолчание: база бота 65 MB при 57 GB
# свободных (замер 10.09.2026); каталог того же порядка. Десять снимков —
# порядок величины несущественный, и печать занятого места ниже отвечает не
# на «сколько взять», а на «не разошлось ли».
KEEP="${PG_SNAPSHOT_KEEP:-10}"
BACKUP_PATH="$BACKUP_DIR/pre-deploy-$(date +%Y%m%d-%H%M%S).sql.gz"

# Кто и куда пишет — В ЛОГ, первой строкой и числом: имя учётки на раннере
# маскируется как секрет, uid — нет.
echo "::notice::снимок: пишет uid $(id -u), внутри контейнера uid $OWNER_UID:$OWNER_GID, каталог $BACKUP_DIR"
mkdir -p "$BACKUP_DIR"

# Проверка записи ДО pg_dump тем же пользователем: иначе первым о правах
# сказал бы pg_dump, и отказ читался бы как сбой базы.
PROBE="$BACKUP_DIR/.write-probe.$$"
if ! (: > "$PROBE") 2>/dev/null; then
  echo "::error::каталог снимков не записываем: $BACKUP_DIR" >&2
  exit 1
fi
rm -f "$PROBE"

# Пользователь и имя базы — ИЗ КОНТЕЙНЕРА, не вписаны сюда: пилот поднимается
# со своим .env, значений которого в репозитории нет. Кавычки вокруг переменных
# внутри одинарных — чтобы их раскрыл sh в контейнере, а не хост.
docker compose exec -T --user "$OWNER_UID:$OWNER_GID" db \
  sh -c 'pg_dump -U "$POSTGRES_USER" "$POSTGRES_DB"' | gzip > "$BACKUP_PATH"

# Ноль обязан иметь положительную стражу: pg_dump, упавший внутри пайпа,
# оставляет валидный gzip-заголовок в два десятка байт — «файл есть, размер
# ненулевой, данных нет» прошло бы за успех.
SIZE="$(stat -c %s "$BACKUP_PATH")"
if [ "$SIZE" -lt 1024 ]; then
  echo "::error::снимок слишком мал ($SIZE байт) — отказ ДО любых изменений на хосте" >&2
  exit 1
fi
echo "Snapshot: $BACKUP_PATH ($SIZE bytes)"

# Ротация по ИМЕНИ в обратном порядке: имя несёт метку времени снимка и не
# сдвинется от постороннего касания файла.
ls -1 "$BACKUP_DIR"/pre-deploy-*.sql.gz 2>/dev/null | sort -r | tail -n +$((KEEP + 1)) \
  | while read -r OLD; do rm -f "$OLD"; done
KEPT="$(ls -1 "$BACKUP_DIR"/pre-deploy-*.sql.gz 2>/dev/null | wc -l)"
TOTAL="$(du -sh "$BACKUP_DIR" | cut -f1)"
echo "::notice::снимков в $BACKUP_DIR: $KEPT (глубина $KEEP), занято $TOTAL"
