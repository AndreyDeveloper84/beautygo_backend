"""Распознавание НАЗВАННОЙ услуги в свободном тексте цели.

DRF-1451 — зачем это существует
--------------------------------

Владелец 03.09.2026: рядом с вопросами анкеты должен стоять запрос уже
известной услуги. Человек со словами «хочу маникюр» называет её прямо на
поверхности анкеты и идёт к подбору, **не отвечая ни на один вопрос**
(поправка A-1 к BOT-001, §24, условие C-2).

Почему это НЕ нечёткий маппинг (OD-1 не нарушен)
-------------------------------------------------

Порога уверенности здесь нет и близости здесь нет. Есть три
детерминированных условия, каждое из которых либо выполнено, либо нет:

1. известное имя целиком присутствует в тексте как непрерывная цепочка
   слов — с точностью до словарной формы каждого слова (DRF-1461);
2. всё, что в тексте осталось за пределами имени, — обрамление, то
   есть слово из закрытого списка ниже (DRF-1461);
3. имя есть в каталоге — в прайсе **любого** салона или в общей
   таксономии (DRF-1472).

Ни расстояния Левенштейна, ни эмбеддингов, ни «ближайшего», ни числа,
которое можно подкрутить. На одинаковом входе и одинаковом каталоге
ответ всегда один.

DRF-1461 — падежи, и почему одной морфологии мало
--------------------------------------------------

Решение владельца 04.09.2026 разрешило морфологическую нормализацию:
«маникюра» -> «маникюр». Сама по себе она чинит только половину замера —
и **ухудшает** вторую. В каталоге пилота есть категория «Уход», а фраза
«нужен уход за собой» содержит слово «уход» дословно и потому уже
сегодня распознаётся как эта услуга, ошибочно. Лемматизация такие
случаи усиливает: словоформ, приводящихся к «уход», становится больше.

Поэтому вместе с послаблением вводится ограничение — **обрамление**.
Названная услуга это текст, состоящий из имени услуги и служебных слов
вокруг него, и ничего больше:

    «хочу маникюра»          -> [хотеть] + «маникюр»            OK
    «записаться на маникюр»  -> [записаться, на] + «маникюр»    OK
    «нужен уход за собой»    -> [нужный] + «уход» + [за, себя]  отказ

«за» и «себя» — не обрамление, а содержание: человек сказал про себя
что-то, чего в имени услуги нет. Значит, услуга не названа, а помянута,
и решать по ней нельзя.

Список обрамления закрыт и лежит в этом файле — его можно прочитать
целиком и оспорить построчно. Это его главное свойство: он не
настраивается по данным и не подкручивается, потому что подкручивать
было бы нечем (OD-2 — корпуса формулировок нет).

Правило намеренно строгое в одну сторону. Не распознали — человек
получает уточнение и кнопку «Найти услугу», то есть доходит до подбора
другим путём; распознали неверно — человека ведут к услуге, которую он
не называл. Цена ошибок разная, поэтому и осторожность односторонняя.

DRF-1472 — каталог всех салонов, и почему салона здесь нет вовсе
-----------------------------------------------------------------

DRF-1455 сузил поиск до каталога салона клиента. Владелец 04.09.2026
это отменил, разобравшись, как устроены боты: цели спрашивают **только
в клиентском боте**. Он один, общий, и салон у него не задан нарочно —
это витрина. Салонный бот существует для владельцев салонов и целей не
спрашивает; ``MAX_BOT_SALON_TENANT_SLUG`` — особенность пилота с одним
салоном, а не «бот салона Формула тела».

Значит случая «клиент пришёл через бота салона» не существует: клиент
всегда на витрине, и показать ему все салоны, у которых нужная услуга
есть, — не утечка, а смысл продукта. Поэтому салона в этом решении нет
ни в каком виде: ни аргументом, ни колонкой на цели.

Граница остаётся ровно одна, и она не салонная: услуги, которой нет
**ни у одного** салона, не существует и для распознавания — человек
получает уточнение и выход «Найти услугу».

Чем платим: голый фильтр по ``is_active`` читает ``SalonService``
последовательно, мимо индексов, начинающихся с ``tenant``. Держат это
кеш на ``_CACHE_TTL_SECONDS`` и потолок ``MAX_CATALOG_NAMES``, ниже.
"""
from __future__ import annotations

import re
from dataclasses import dataclass

from django.core.cache import cache

from services.models import SalonService, ServiceCategory

from .morphology import normalize_all

# Всё, что не буква и не цифра, — разделитель. Дефисы и точки внутри
# названий («аппаратный маникюр», «SPA-уход») распадаются на слова
# одинаково с обеих сторон сравнения, поэтому совпадение не теряется.
_WORD_RE = re.compile(r"[^\w]+", flags=re.UNICODE)

# Потолок длины текста, в котором мы вообще ищем имя услуги. Короткая
# фраза («хочу маникюр») — это название услуги с обрамлением. Длинный
# рассказ — это цель своими словами, и выдёргивать из него совпавшее
# слово значило бы угадывать, чего человек хочет.
MAX_TEXT_WORDS = 12

#: Обрамление — слова, которые вокруг названия услуги ничего к нему не
#: добавляют. Список закрыт: всё, чего в нём нет, считается содержанием,
#: и текст с таким словом за пределами имени услугой не признаётся.
#:
#: Записаны поверхностные формы, а НЕ леммы, и приводятся к словарной
#: форме тем же ``normalize_all``, что и текст пользователя. Так список
#: остаётся согласованным с разборщиком сам собой: «нужен» -> «нужный»,
#: «мне» -> «я» — угадывать, во что именно словарь превратит слово, не
#: нужно никому.
#:
#: Чего здесь сознательно НЕТ:
#: - «за», «про», «для», «с», «под» — предлоги, вводящие содержание
#:   («уход ЗА СОБОЙ», «крем ДЛЯ РУК»). Именно «за» и отсекает ложное
#:   срабатывание из замера DRF-1461;
#: - «себя»/«собой» — то же самое: это про человека, а не про услугу;
#: - «сегодня», «завтра», «недорого» — содержательные уточнения. Не
#:   вредны, но и не проверены на реальных фразах; добавлять их надо
#:   отдельным решением с замером, а не заодно.
_FRAME_SURFACE: tuple[str, ...] = (
    # намерение
    "хочу", "хочется", "хотел", "хотела", "хотелось", "хотим",
    "нужен", "нужна", "нужно", "нужны", "надо", "требуется",
    "интересует", "интересно",
    # действие
    "записаться", "записать", "запись", "запиши", "записывай",
    "сделать", "делать", "сходить", "пойти", "посетить", "попасть",
    # адресация и вежливость
    "я", "мне", "меня", "мы", "нам", "можно", "пожалуйста",
    "подскажите", "подскажи",
    # предлоги, которые вводят только само имя услуги
    "на", "в", "к",
    # частицы
    "бы", "же", "ли",
)


@dataclass(frozen=True)
class NamedService:
    """Найденное в тексте имя из каталога."""

    kind: str  # "category" | "service"
    name: str


def _words(value: str) -> list[str]:
    return [w for w in _WORD_RE.split(value.casefold()) if w]


def _frame_lemmas() -> frozenset[str]:
    """Обрамление в словарных формах.

    Не кешируется отдельно: тяжёлая часть — разбор слова — уже лежит в
    ``lru_cache`` лемматизатора, а флаг морфологии тесты переключают
    на лету, и замороженный здесь набор от них бы отстал.
    """
    return frozenset(normalize_all(_FRAME_SURFACE))


def _sequence_spans(haystack: tuple[str, ...], needle: tuple[str, ...]) -> list[int]:
    """Индексы начал вхождений ``needle`` в ``haystack`` как цепочки слов."""
    if not needle or len(needle) > len(haystack):
        return []
    size = len(needle)
    return [
        i
        for i in range(len(haystack) - size + 1)
        if haystack[i:i + size] == needle
    ]


def _only_frame_around(
    haystack: tuple[str, ...], start: int, size: int, frame: frozenset[str],
) -> bool:
    """Всё ли вне отрезка ``[start, start + size)`` — обрамление."""
    rest = haystack[:start] + haystack[start + size:]
    return all(word in frame for word in rest)


#: Ключ и срок кеша списка имён. Каталог меняется редко, а читается
#: теперь на каждом открытии приложения. Версия ``v3`` — в кеше лежит
#: каталог всех салонов одной записью (DRF-1472), и записи ``v2``,
#: разложенные по салонам, ему не соответствуют.
_CACHE_KEY = "goals.service_match.catalog_names.v3"
_CACHE_TTL_SECONDS = 300

#: Потолок числа имён. Не оптимизация, а предохранитель: без него
#: зеркало YClients на тысяче салонов превращает каждую проверку в
#: последовательное чтение всей таблицы услуг.
MAX_CATALOG_NAMES = 5000


def _load_catalog() -> list[tuple[str, str, tuple[str, ...]]]:
    """``(kind, name, лемматизированные слова имени)`` — весь каталог.

    Категории и услуги читаются целиком, по всем салонам: клиентский
    бот — витрина, салона у него нет, и услуга, которая есть хоть у
    одного салона, человеку доступна (DRF-1472).

    Категории идут первыми не по важности, а чтобы потолок
    ``MAX_CATALOG_NAMES`` срезал сначала прайсы: общая таксономия
    ``ServiceCategory`` — десятки строк владельца, ``SalonService`` —
    тысячи строк зеркала, и терять надо второе.
    """
    rows: list[tuple[str, str, tuple[str, ...]]] = [
        ("category", name, normalize_all(_words(name)))
        for name in ServiceCategory.objects.filter(is_active=True)
        .order_by("name")
        .values_list("name", flat=True)[:MAX_CATALOG_NAMES]
    ]
    remaining = MAX_CATALOG_NAMES - len(rows)
    if remaining > 0:
        rows += [
            ("service", name, normalize_all(_words(name)))
            for name in SalonService.objects.filter(is_active=True)
            .order_by("name")
            .values_list("name", flat=True)[:remaining]
        ]
    return rows


def _catalog() -> list[tuple[str, str, tuple[str, ...]]]:
    """Активные имена каталога — категории и услуги всех салонов.

    # Кеш

    Функция вызывается из ``build_decision_context``, то есть на каждом
    открытии приложения и на каждом ответе сервера, для любого клиента
    с текстовой целью. Пятиминутный кеш и потолок ``MAX_CATALOG_NAMES``
    держат стоимость ограниченной; каталог меняется несравнимо реже.
    Ключ один на всех: каталог теперь один на всех.

    В кеше лежат уже лемматизированные слова: разбор каталога стоит
    заметно дороже разбора одной короткой фразы, и платить за него на
    каждый запрос незачем.
    """
    cached = cache.get(_CACHE_KEY)
    if cached is None:
        cached = _load_catalog()
        cache.set(_CACHE_KEY, cached, _CACHE_TTL_SECONDS)
    return [(kind, name, tuple(lemmas)) for kind, name, lemmas in cached]


def match_named_service(text: str | None) -> NamedService | None:
    """Названа ли в ``text`` услуга или категория каталога.

    Каталог — весь, по всем салонам (DRF-1472). Салона у этой функции
    нет и не должно быть: цели спрашивает клиентский бот-витрина, и
    услуга, которая есть хоть у одного салона, человеку доступна.

    ``None`` в ответе — не названа, то есть такого имени нет ни у
    одного салона. Тогда цель остаётся неразрешённой и документ, как и
    раньше, просит уточнить (``goal_clarification``), сохраняя выход
    «Найти услугу».
    """
    if not text:
        return None

    surface = _words(text)
    if not surface or len(surface) > MAX_TEXT_WORDS:
        # Длинный рассказ — это не «названная услуга», а формулировка
        # цели своими словами. Разбирать её здесь значило бы угадывать.
        return None

    haystack = normalize_all(surface)
    frame = _frame_lemmas()

    best: NamedService | None = None
    best_len = 0
    for kind, name, needle in _catalog():
        size = len(needle)
        if not size or size < best_len:
            continue
        spans = _sequence_spans(haystack, needle)
        if not spans:
            continue
        if not any(
            _only_frame_around(haystack, start, size, frame) for start in spans
        ):
            # Имя в тексте есть, но вокруг него осталось содержание —
            # услуга помянута, а не названа. См. «нужен уход за собой».
            continue
        if size > best_len or (
            size == best_len and best is not None and name < best.name
        ):
            best, best_len = NamedService(kind=kind, name=name), size
    return best
