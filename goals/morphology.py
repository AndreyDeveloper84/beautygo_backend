"""Морфологическая нормализация русского слова (DRF-1461).

Что здесь разрешено, и чем это отличается от запрещённого
----------------------------------------------------------

Решение владельца 04.09.2026 сняло запрет OD-1 **узко**: разрешена
морфологическая нормализация — приведение словоформы к словарной,
«маникюра» → «маникюр». Осталось запрещено то, что OD-1 запрещал на
самом деле: порог уверенности и совпадение «по похожести».

Разница не стилистическая. Лемматизация — детерминированное
преобразование по правилам языка и фиксированному словарю: у слова
«маникюра» ровно одна словарная форма, и она не зависит ни от каких
настраиваемых чисел. Совпадение «по похожести» требовало бы ответа на
вопрос «насколько похоже достаточно» — то есть порога, калибровать
который OD-2 не на чем (корпуса формулировок нет).

Поэтому здесь нет ни одного числа, которое можно было бы подкрутить.
``parse(word)[0].normal_form`` — первый разбор словаря, взятый
безусловно; никакой ``score`` ни с чем не сравнивается. На одном и том
же слове и одной и той же версии словаря ответ всегда один.

Почему pymorphy3, а не самописный отсекатель окончаний
------------------------------------------------------

Отсечение окончаний по правилам — это стемминг, а не лемматизация: он
склеивает несвязанные слова (классический пример — «уха» и «ухо»), и
именно склейки нам здесь дороже всего, потому что каждая склейка это
новое ложное срабатывание. Владелец разрешил «приведение словоформы к
словарной» — словарь и есть то, что делает операцию проверяемой.

pymorphy2 на Python 3.12 не работает (снятый в 3.11
``inspect.getargspec``); pymorphy3 — поддерживаемый форк того же
словаря OpenCorpora.

Мягкий отказ
------------

Если библиотека почему-либо не встала, ``normalize`` вырождается в
тождество — и матчинг возвращается ровно к дословному сравнению, то
есть к поведению до DRF-1461. Это строгое сужение, а не другое
поведение: ни одно совпадение, которого без морфологии не было, при
отказе не появится. Тот же выключатель доступен явно —
``GOAL_SERVICE_MATCH_MORPHOLOGY = False``.
"""
from __future__ import annotations

import logging
from functools import lru_cache
from typing import Any

from django.conf import settings

logger = logging.getLogger(__name__)

_UNAVAILABLE_LOGGED = False


@lru_cache(maxsize=1)
def _analyzer() -> Any | None:
    """Единственный на процесс разборщик. ``None`` — библиотеки нет.

    ``MorphAnalyzer()`` разворачивает словарь OpenCorpora в память
    (десятки МБ) и стоит ~0.4 с — на запрос его создавать нельзя.
    ``lru_cache`` держит один экземпляр на процесс; он потокобезопасен
    на чтение. Цена платится один раз, на первой распознаваемой цели
    после старта воркера, а не на импорте: гонять словарь в память ради
    ``manage.py migrate`` незачем.

    Сам разбор дешёвый — ~0.15 мс на слово, и ``_lemma`` его ещё и
    кеширует. Дороже всего разовый разбор каталога на промах кеша имён
    (``service_match._catalog``): при потолке ``MAX_CATALOG_NAMES``
    это порядка двух секунд в худшем случае и десятки миллисекунд на
    реальном каталоге салона, раз в пять минут.
    """
    global _UNAVAILABLE_LOGGED
    try:
        import pymorphy3
    except ImportError:  # pragma: no cover - зависит от окружения
        if not _UNAVAILABLE_LOGGED:
            logger.warning(
                "goals.morphology.unavailable: pymorphy3 not installed; "
                "service match falls back to literal word comparison"
            )
            _UNAVAILABLE_LOGGED = True
        return None
    return pymorphy3.MorphAnalyzer()


def is_enabled() -> bool:
    """Включена ли нормализация. Умолчание — ON."""
    return bool(getattr(settings, "GOAL_SERVICE_MATCH_MORPHOLOGY", True))


@lru_cache(maxsize=20000)
def _lemma(word: str) -> str:
    morph = _analyzer()
    if morph is None:
        return word
    parses = morph.parse(word)
    if not parses:  # pragma: no cover - pymorphy всегда что-то возвращает
        return word
    return parses[0].normal_form


def normalize(word: str) -> str:
    """Словарная форма слова. Выключенная морфология — тождество."""
    if not is_enabled():
        return word
    return _lemma(word)


def normalize_all(words: tuple[str, ...] | list[str]) -> tuple[str, ...]:
    """Словарные формы цепочки слов, порядок сохраняется."""
    if not is_enabled():
        return tuple(words)
    return tuple(_lemma(w) for w in words)


def reset_cache() -> None:
    """Сбросить кеш лемм — для тестов, переключающих флаг."""
    _lemma.cache_clear()
