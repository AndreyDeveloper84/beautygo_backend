"""Подключение резолвера цели к выдаче — единственное место, где
читается ``GOAL_RESOLUTION_ENABLED`` (OD-1).

Зачем отдельный модуль
----------------------
``goals.resolution.resolve_goal_category_ids`` — чистая функция и
таковой остаётся. Флаг и политика «что делать, когда разрешить нельзя»
— это уже решение вызывающей стороны, и оно должно быть записано ОДИН
раз, а не повторено в каждой точке подключения. Иначе две выдачи
разъедутся в трактовке ``None``, и разъедутся молча.

Политика при ``None`` (решение OD-1, 2026-08-29)
------------------------------------------------
Докстринг резолвера требует: «вызывающая сторона обязана уточнить, а не
угадывать». Здесь это прочитано буквально — как **запрет угадывать**, а
не как требование допрашивать клиента на каждом экране:

* ``None`` → **фильтр по цели не применяется, выдача остаётся прежней.**
  Невыбранная цель не влияет ни на что; выдача при этом не делает
  никакого утверждения о цели, то есть ничего не угадывает.
* Уточнение при этом НЕ теряется: за него отвечает уже существующая
  поверхность целевого слоя — ``goals.decision_context``, которая на том
  же состоянии отдаёт ``missing: [{kind: "goal"|"goal_clarification"}]``
  вместе с подсказками. Спрашивать второй раз с полки выдачи незачем.

Почему не «пустая выдача» и не «уточняющий вопрос вместо выдачи»:
на пилоте ``ClientGoal`` = 0, то есть ветка ``None`` — это сегодня
поведение **для 100% пользователей**, а не редкий край. Превратить её в
допрос или в пустой экран значит выкатить регресс всем и замаскировать
его под фичу. Обратное решение владелец может принять отдельно; здесь
оно намеренно не принимается за него.

Что НЕ различается
------------------
Резолвер схлопывает «цели нет», «маппинга нет» и «цель разрешилась в
ноль категорий» в один ``None`` (``_categories_for_option(...) or None``
в ``goals/resolution.py``). Для политики выше это безразлично — все три
случая ведут к прежней выдаче, — но диагностически это потеря: цель без
единой связи выглядит как отсутствие цели. Поэтому ниже она логируется
отдельно: на пилоте это единственный способ заметить незакураированную
цель, и стоит она один дешёвый запрос, только при включённом флаге.

Что происходит при пустом результате фильтра
--------------------------------------------
Ничего: фолбэка на неотфильтрованную выдачу здесь НЕТ. Цель, которая
разрешилась, обязана резать по-настоящему, иначе её влияние
недетерминировано и непроверяемо на бою. Пустая полка при разрешённой
цели — это дефект курирования каталога, и он должен быть виден
(``goal.filter_empty`` в логе), а не замаскирован.
"""
from __future__ import annotations

import logging
from uuid import UUID

from django.conf import settings

from .models import ClientGoal
from .resolution import resolve_goal_category_ids

logger = logging.getLogger(__name__)


def goal_resolution_enabled() -> bool:
    """Единственное чтение флага во всём репозитории."""
    return bool(getattr(settings, "GOAL_RESOLUTION_ENABLED", False))


def goal_category_ids_for(client) -> tuple[UUID, ...] | None:
    """Категории активной цели клиента, либо ``None`` — «не фильтровать».

    ``None`` возвращается и при выключенном флаге, и когда резолвер не
    смог разрешить цель. Вызывающая сторона в обоих случаях обязана
    отдать прежнюю выдачу: см. политику в докстринге модуля.

    Кортеж (а не список) — потому что ``RecommendationQuery`` заморожен
    и обязан оставаться хешируемым для ключа кэша.
    """
    if not goal_resolution_enabled():
        return None

    resolved = resolve_goal_category_ids(client)
    if not resolved:
        _log_unresolved(client)
        return None

    logger.info(
        "goal.resolved client_id=%s categories=%d", client.id, len(resolved),
    )
    return tuple(resolved)


def _log_unresolved(client) -> None:
    """Отделить «цели нет» от «цель есть, но не разрешается».

    Резолвер эти случаи схлопывает, а для пилота разница
    принципиальная: первое — норма (никто ещё не выбирал цель),
    второе — незакураированная связь, то есть подсказка, которая
    клиенту показана, а выдачу не меняет.
    """
    has_goal = ClientGoal.objects.filter(client=client, is_active=True).exists()
    if has_goal:
        logger.warning(
            "goal.unresolved client_id=%s — активная цель есть, но категорий "
            "нет (нет связей GoalOptionCategory либо свободный текст без "
            "точного совпадения); выдача остаётся прежней",
            client.id,
        )
    else:
        logger.debug("goal.absent client_id=%s", client.id)
