"""Граница каталога отказывается принимать параметры тела без основания.

Решение владельца §92 (10.09.2026): «Сегодняшнее поведение — вес
спрашивается без согласия — прекращается. Это была единственная горящая
поверхность на живых людях».

### Что каталог проверяет, а что нет

Каталог **не судит о согласии** и не хранит его. Реестр согласий живёт в
боте (`apps/consent/models.py::ConsentRecord`), и заводить второй здесь —
значит через месяц получить два расходящихся реестра, причём расхождение
обнаружится ровно тогда, когда кто-то уже что-то записал не туда.

Поэтому граница требует не проверки, а **утверждения**: вызывающий
называет вид согласия и версию текста, под которой оно получено. Без
утверждения — отказ. Каталог отвечает за то, чтобы **отсутствие
утверждения не читалось как «согласие есть»** — сегодня читается именно
так, и шесть профилей пилота собраны до того, как согласие требуемого
вида вообще начало существовать.

Версия обязательна, а не булев признак: согласие без версии через полгода
нельзя отличить от согласия на другой текст. §92 требует того же прямо —
«версия текста, дата, способ получения и отзыв согласия сохраняются».

### Какие поля закрыты

§92 перечисляет состав «Персонального расчёта» дословно: вес, рост,
возраст, физиологический пол, активность и цель. Шесть.

``weight_range`` добавлен седьмым **осознанно**: это тот же вес меньшего
разрешения, и пропустить его значило бы закрыть парадную дверь, оставив
рядом окно. Решение моё, не владельца, и названо здесь, чтобы его можно
было оспорить.

``pace`` НЕ закрыт: §92 называет цель, а не темп, и темп сам по себе о
теле ничего не сообщает. ``diet_preference`` и ``timezone`` — не
параметры тела. ``health_flags`` живут под своим согласием (``health``) и
этим сторожем не трогаются.

### Предел этого среза

Сторож закрывает приём **новых** данных. Четыре веса, уже лежащие в базе
пилота (65.0, 67.0, 90.0, 95.0 на 10.09.2026), он не трогает: что с ними
делать — удалить, обезличить или спросить людей задним числом — решение
владельца, оно в реестре открытых решений. Названный предел лучше
умолчания.
"""
from __future__ import annotations

from typing import Any

#: Поля, которые §92 относит к «Персональному расчёту».
PERSONAL_CALCULATION_FIELDS = frozenset({
    "gender",
    "age",
    "height_cm",
    "weight_kg",
    "weight_range",
    "activity_coefficient",
    "goal",
})

#: Вид согласия, под которым эти поля принимаются. Совпадает со значением
#: ``ConsentRecord.ConsentType.PERSONAL_CALCULATION`` в боте — это
#: контракт границы, а не совпадение имён.
PERSONAL_CALCULATION = "personal_calculation"

#: Машинный код отказа. Свой, а не общий ``VALIDATION_ERROR``: вызывающему
#: нужно отличить «данные невалидны» (чинится телом запроса) от «нет
#: основания их принимать» (чинится согласием человека). По статусу
#: причину восстановить нельзя — 422 в этом репозитории уже носят
#: несколько разных отказов.
CONSENT_REQUIRED = "CONSENT_REQUIRED"


class PersonalCalculationConsentRequired(Exception):
    """Запрос принёс параметры тела без утверждения о согласии.

    Несёт список полей, которые были отвергнуты, — чтобы вызывающий
    чинил своё утверждение, а не угадывал, что именно не понравилось.
    """

    code = CONSENT_REQUIRED

    def __init__(self, fields: list[str]) -> None:
        self.fields = sorted(fields)
        super().__init__(
            "Параметры тела принимаются только с утверждением о согласии "
            f"вида {PERSONAL_CALCULATION!r}: {self.fields}"
        )


def gated_fields_in(payload: dict[str, Any]) -> set[str]:
    """Какие закрытые поля несёт этот запрос.

    Смотрит на ПРИСУТСТВИЕ ключа, а не на истинность значения: ручка
    PATCH-семантичная, и `weight_kg: 0` — это тоже утверждение о теле.
    """
    return {f for f in PERSONAL_CALCULATION_FIELDS if f in payload}


def require_consent(payload: dict[str, Any]) -> None:
    """Пропустить запрос дальше — или отказать, если основания нет.

    Fail-closed: отсутствие утверждения — отказ, а не разрешение. Это тот
    же приём, что у медицинского гейта: отказ вместо догадки.
    """
    gated = gated_fields_in(payload)
    if not gated:
        # Запрос не несёт параметров тела — согласие этого вида ему не
        # нужно, и требовать его значило бы закрыть дневник ради
        # расчёта. §92: «отказ не закрывает дневник».
        return

    attestation = payload.get("consent")
    if not isinstance(attestation, dict):
        raise PersonalCalculationConsentRequired(list(gated))

    if attestation.get("type") != PERSONAL_CALCULATION:
        raise PersonalCalculationConsentRequired(list(gated))

    version = attestation.get("document_version")
    if not isinstance(version, str) or not version.strip():
        # Версия обязательна: см. докстринг модуля и §92.
        raise PersonalCalculationConsentRequired(list(gated))
