"""Тип питания: что считается ответом, а что — прежним значением (DRF-2310).

# Откуда список

Состав назвал владелец 23.09.2026 (§77 п. 5): «без ограничений ·
вегетарианство · веганство · кето · халяль · кошер · другое словами».
Состав совпал со словарём команд забывания бота
(``apps/persona/memory_commands.py``), и это совпадение, а не основание:
тот словарь — матчер фраз («забудь, что я веган»), он не решает, что
человека спрашивают. Происхождение списка — слово владельца; если однажды
списки разойдутся, разойтись им положено именно так.

# Почему «без ограничений» — не ``none``

У колонки ``diet_preference`` стоит умолчание ``"none"``, и оно лежит в
каждой строке, заведённой до вопроса. Возьми код ``none`` под «без
ограничений» — и все эти люди молча оказались бы ответившими «ем всё», хотя
их никто не спрашивал. Поэтому у ответа свой код ``unrestricted``, а
``none`` остаётся тем, чем всегда был: следом умолчания, а не ответом.

# Три разных состояния, которые нельзя смешивать

* **ответ** — значение из списка, названное человеком;
* **пропуск** — человек вопрос видел и отвечать не стал. Решение владельца
  (§77 п. 6): это НЕ «без ограничений». Первое — отсутствие ответа, второе
  — ответ, и смешать их значит записать человеку слова, которых он не
  говорил. Пропуск живёт там же, где пропуски остальных вопросов анкеты —
  ``health_flags["diet_preference_skipped"]``;
* **прежнее значение** — то, что лежало в колонке до вопроса. Решение
  владельца (§77 п. 7): хранить молча, не стирать, кампании переспроса не
  устраивать — но шаг считать НЕПРОЙДЕННЫМ, иначе человек со старым ``any``
  остался бы с неизвестным типом питания навсегда и не был бы спрошен ни
  разу. Отмечается тем же механизмом, что темп и активность в DRF-2279:
  имя поля в ``legacy_default_inputs``. Второй такой же механизм заводить
  не стали — разошлись бы они молча.

Названный ответ снимает пометку прежнего значения, в том числе когда
значение то же самое: это подтверждение, и оно ровно то же, что у
``pace``/``activity_coefficient`` (``profile_upsert_service``).
"""
from __future__ import annotations

from nutrition.models import NutritionProfile

#: Имя поля — одно на все три места: пометка легаси, флаг пропуска, ответ.
DIET_FIELD = "diet_preference"

#: Умолчание столбца, которое ручка отдаёт наружу и вызывающие возвращают
#: обратно. Это НЕ ответ и не значение списка — эхо, которое принимают и
#: игнорируют, иначе обычный read-modify-write ломался бы отказом.
LEGACY_DIET_ECHO = "none"

#: Флаг пропуска — та же форма, что у остальных вопросов анкеты.
DIET_SKIPPED_FLAG = f"{DIET_FIELD}_skipped"


def diet_answered(profile: NutritionProfile) -> bool:
    """Назвал ли человек свой тип питания.

    Три причины ответить «нет» при непустой колонке: значение не из списка
    (``none`` умолчания, старое ``any``, любая прежняя строка), значение
    помечено как прежнее (``legacy_default_inputs``), либо это «другое» без
    слов — сказано ничего.
    """
    value = (profile.diet_preference or "").strip()
    if value not in NutritionProfile.DietType.values:
        return False
    if DIET_FIELD in set(profile.legacy_default_inputs or []):
        return False
    if value == NutritionProfile.DietType.OTHER:
        return bool((profile.diet_note or "").strip())
    return True


def answer_diet(profile: NutritionProfile, value: str, *, note: str = "") -> None:
    """Записать ответ: значение, слова для «другого», снятие прежних пометок.

    Ничего не сохраняет в базу — вызывающий решает, когда писать (upsert
    делает это своей транзакцией). Пометка прежнего значения снимается, а
    чужие пометки не трогаются: список общий на несколько полей.
    """
    if value not in NutritionProfile.DietType.values:
        raise ValueError(f"тип питания вне списка владельца: {value!r}")

    profile.diet_preference = value
    profile.diet_note = note.strip() if value == NutritionProfile.DietType.OTHER else ""

    marks = set(profile.legacy_default_inputs or [])
    marks.discard(DIET_FIELD)
    profile.legacy_default_inputs = sorted(marks)

    flags = dict(profile.health_flags or {})
    # Ответ отменяет прежний пропуск: человек всё-таки назвал.
    flags.pop(DIET_SKIPPED_FLAG, None)
    profile.health_flags = flags


def skip_diet(profile: NutritionProfile) -> None:
    """Записать пропуск — и НЕ записать «без ограничений».

    Колонка не трогается намеренно: подставить сюда любое значение значило
    бы выдать молчание за ответ. Прежнее значение, если оно было, остаётся
    лежать как лежало — со своей пометкой.
    """
    flags = dict(profile.health_flags or {})
    flags[DIET_SKIPPED_FLAG] = True
    profile.health_flags = flags
