"""Тип питания: что считается ответом, а что — прежним значением (DRF-2310).

# Откуда список

Состав назвал владелец 23.09.2026 (§77 п. 5): «без ограничений ·
вегетарианство · веганство · кето · халяль · кошер · другое словами».
Состав совпал со словарём команд забывания бота
(``apps/persona/memory_commands.py``), и это совпадение, а не основание:
тот словарь — матчер фраз («забудь, что я веган»), он не решает, что
человека спрашивают. Происхождение списка — слово владельца.

СЛОВАРЬ ОДИН НА КАТАЛОГ — ``users.UserPersonalContext.DietType``. Он старше
этого листа и уже несёт тот самый состав; своего здесь нет намеренно (решение
24.09.2026). Два словаря одного смысла разошлись бы молча — сегодня они уже
расходились ровно в одном значении: «без ограничений» там зовётся
``omnivore``, и код этого значения НЕ меняется, потому что в нём лежат данные
живых людей. Заодно ``omnivore`` не равен умолчанию столбца ``none``, и
прежние строки по-прежнему не сходят за ответ.

# Почему «без ограничений» — не ``none``

У колонки ``diet_preference`` стоит умолчание ``"none"``, и оно лежит в
каждой строке, заведённой до вопроса. Возьми код ``none`` под «без
ограничений» — и все эти люди молча оказались бы ответившими «ем всё», хотя
их никто не спрашивал. Поэтому у ответа свой код ``unrestricted``, а
``none`` остаётся тем, чем всегда был: следом умолчания, а не ответом.

# Три разных состояния, которые нельзя смешивать

* **ответ** — значение из списка, названное человеком;
* **пропуск** — человек вопрос видел и отвечать не стал. Решение владельца
  (§77 п. 6): это НЕ «без ограничений». Первое — отсутствие ответа, второе
  — ответ, и смешать их значит записать человеку слова, которых он не
  говорил. Пропуск живёт там же, где пропуски остальных вопросов анкеты —
  ``health_flags["diet_preference_skipped"]``;
* **прежнее значение** — то, что лежало в колонке до вопроса. Решение
  владельца (§77 п. 7): хранить молча, не стирать, кампании переспроса не
  устраивать — но шаг считать НЕПРОЙДЕННЫМ, иначе человек со старым ``any``
  остался бы с неизвестным типом питания навсегда и не был бы спрошен ни
  разу.

# Почему не пометкой ``legacy_default_inputs`` (DRF-2279)

Тот механизм узнаёт прежнее значение ПО САМОМУ ЗНАЧЕНИЮ: активность 1.4 и
темп «moderate» — это и есть следы умолчаний схемы, человек их не называл.
Здесь так не выходит: «vegan» одинаково может быть и прежней свободной
строкой, и настоящим ответом, и различить их значением нельзя в принципе.
Пометка по значению после выхода вопроса пометила бы КАЖДОГО ответившего и
переспросила бы того, кто уже ответил, — ровно та кампания переспроса,
которой владелец сказал не быть.

Поэтому здесь отмечается не прежнее значение, а сам ФАКТ ответа
(``diet_answered_at``). Он различает эти случаи сам и не требует ни
команды, ни назначенного срока.
"""
from __future__ import annotations

from django.utils import timezone

from nutrition.models import NutritionProfile
from users.models import UserPersonalContext
from users.personal_context_direct_answer import record_direct_answer

#: Словарь значений. Импортируется, а не объявляется здесь.
DietType = UserPersonalContext.DietType

#: Имя поля — одно на все три места: пометка легаси, флаг пропуска, ответ.
DIET_FIELD = "diet_preference"

#: Умолчание столбца, которое ручка отдаёт наружу и вызывающие возвращают
#: обратно. Это НЕ ответ и не значение списка — эхо, которое принимают и
#: игнорируют, иначе обычный read-modify-write ломался бы отказом.
LEGACY_DIET_ECHO = "none"

#: Имя вопроса в ``_skipped_fields`` — КОРОТКОЕ, как у всех остальных
#: пропусков (``weight`` при столбце ``weight_kg``, ``activity`` при
#: ``activity_coefficient``). Возьми здесь имя столбца — и бот, написанный
#: по общему образцу, прислал бы ``"diet"``: пропуск не записался бы, в
#: словаре здоровья завёлся бы неизвестный ключ, следующий же
#: read-modify-write получил бы отказ, а человек молча лишился бы живого
#: комментария модели. Одна опечатка — три немых отказа.
DIET_SKIP_KEY = "diet"

#: Флаг пропуска — та же форма, что у остальных вопросов анкеты.
DIET_SKIPPED_FLAG = f"{DIET_SKIP_KEY}_skipped"


def diet_answered(profile: NutritionProfile) -> bool:
    """Назвал ли человек свой тип питания.

    Три причины ответить «нет» при непустой колонке: ответа не было вовсе
    (``diet_answered_at`` пуст — в столбце прежнее значение), значение не из
    списка, либо это «другое» без слов — сказано ничего.
    """
    if profile.diet_answered_at is None:
        return False
    value = (profile.diet_preference or "").strip()
    if value not in DietType.values:
        return False
    if value == DietType.OTHER:
        return bool((profile.diet_note or "").strip())
    return True


def answer_diet(profile: NutritionProfile, value: str, *, note: str = "") -> None:
    """Записать ответ: значение, слова для «другого», снятие прежних пометок.

    В базу пишет ровно одно — строку личного контекста (память ИИ): она
    ЖИВЁТ отдельно от профиля, и оставить её вызывающему значило бы
    разрешить расхождение, ради которого §77 п. 3 и написан. Сам профиль не
    сохраняется: этим распоряжается upsert своей транзакцией.
    """
    if value not in DietType.values:
        raise ValueError(f"тип питания вне списка владельца: {value!r}")

    profile.diet_preference = value
    profile.diet_note = note.strip() if value == DietType.OTHER else ""
    profile.diet_answered_at = timezone.now()

    # §77 п. 3: прямой ответ доезжает до памяти ИИ, иначе подсказка модели
    # продолжит называть прежнюю диету, выведенную из разговора, — и человек
    # увидит в выгрузке два разных ответа на один вопрос. Источник
    # ``explicit`` делает названное отличимым от выведенного; «прямой ответ
    # главнее выведенного» без этой пометки нечем исполнить.
    record_direct_answer(profile.user, "diet_type", value)

    flags = dict(profile.health_flags or {})
    # Ответ отменяет прежний пропуск: человек всё-таки назвал.
    flags.pop(DIET_SKIPPED_FLAG, None)
    profile.health_flags = flags


def skip_diet(profile: NutritionProfile) -> None:
    """Записать пропуск — и НЕ записать «без ограничений».

    Колонка не трогается намеренно: подставить сюда любое значение значило
    бы выдать молчание за ответ. Прежнее значение, если оно было, остаётся
    лежать как лежало.

    **Пропуск поверх ответа ничего не пишет.** Человек, уже назвавший свой
    тип, вопроса не видит — спрашивают только при ``diet_answered() is
    False``. Приди пропуск всё равно (старый клиент, повтор тела), флаг
    рядом с настоящим ответом означал бы два противоположных факта об одном
    вопросе: «назвал» и «не назвал». Ответ старше и сильнее — он остаётся,
    а пропуск не записывается.
    """
    if diet_answered(profile):
        return
    flags = dict(profile.health_flags or {})
    flags[DIET_SKIPPED_FLAG] = True
    profile.health_flags = flags
