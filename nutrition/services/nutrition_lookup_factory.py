"""Одна дверь, через которую справочник питания собирается для боя (DRF-2334).

`NutritionLookup` по замыслу трёхслойная — seed → официальный источник →
оценка, — но слои приходят через DI, и до этого листа **все четыре боевых
места собирали её пустым конструктором**. В пилоте работал только seed из
54 блюд: любое блюдо вне него возвращало карточку без калорий, а записать
такую карточку каталог отказывался (DRF-2371 снял отказ: запись теперь
ложится без чисел, но слой от этого не стал нужен меньше). Слой существовал и не вызывался ни разу.

Чтобы это не повторилось молча, конструктор в бою не зовут напрямую — зовут
`build_nutrition_lookup()`. Сторож `test_usda_layer_wired_2334` обходит боевые
файлы и краснеет на любой прямой сборке.

**Выключено по умолчанию.** `USDA_LOOKUP_ENABLED` открывает слой на стенде
после проверки владельцем; ключ и лимиты — его вопрос. Выключенный слой ведёт
себя ровно как «слоя нет» и аварией не считается: справочник отвечает тем, что
знает сам.

**Штатный отказ внешнего справочника — не наша авария.** Ни выключенность, ни
ненастроенность, ни падение источника не превращают скан в 5xx и не будят
тревогу: общий предохранитель бота считает стойкий 5xx аварией, и кормить его
чужим простоем нельзя.

**Журнал различает четыре исхода** — и «выключено» среди них (DRF-2381):

* ``layer_absent reason=disabled`` (INFO) — выключено владельцем;
* ``layer_absent reason=not_configured`` (WARNING) — включено, но без ключа;
  это наша недонастройка, её чинит человек;
* ``nutrition.usda.miss`` (INFO) — источник ответил, блюда у него нет;
* ``nutrition.usda.unavailable`` (WARNING) — источник отказал.

Раньше выключенность молчала, и это было записано как замысел. Замысел
поменялся по той же причине, что у `booking.auto_complete.pass ran=false`
(DRF-1048): «слой выключен» и «слой включён и ничего не нашёл» выглядели в
пустом журнале одинаково, а чинятся по-разному. Молчание — не состояние.

**Слой оценки не подключается.** По решению владельца (вопрос 40) ИИ распознаёт
входные данные, а считает backend; роль `micronutrient_estimator` в цепочке
расчёта — отдельный вопрос, и до ответа его здесь нет.
"""

from __future__ import annotations

import logging

from django.conf import settings

from nutrition.services.nutrition_lookup import NutritionLookup
from nutrition.services.usda_lookup import USDALookup

logger = logging.getLogger(__name__)

__all__ = ["build_nutrition_lookup"]


def build_nutrition_lookup() -> NutritionLookup:
    """Справочник питания для боевого пути. Единственная сборка."""
    return NutritionLookup(usda_lookup=_usda_layer())


def _usda_layer() -> USDALookup | None:
    """Слой официального источника, или ``None``, если его сейчас нет.

    ``None`` — рабочее состояние, а не сбой: справочник просто отвечает тем,
    что знает сам. Но состояние это **называется вслух**: выключено — INFO,
    включено без ключа — WARNING (второе чинит человек).
    """
    if not getattr(settings, "USDA_LOOKUP_ENABLED", False):
        # DRF-2381. Раньше здесь был молчаливый `return None`, и это было
        # записано как замысел. Беда в том, что в пустом журнале «слой
        # выключен» неотличимо от «слой включён и ничего не нашёл», а чинят
        # эти два состояния разными руками. Строка INFO, одна, и в ней
        # названа переменная, которая это меняет, — как у
        # `booking.auto_complete.pass ran=false` (DRF-1048).
        logger.info("nutrition.usda.layer_absent reason=disabled (USDA_LOOKUP_ENABLED)")
        return None
    try:
        return USDALookup()
    except ValueError:
        # Включён без ключа. Это наша недонастройка, и её надо увидеть — но
        # скан от неё не падает и тревогу она не поднимает.
        logger.warning("nutrition.usda.layer_absent reason=not_configured")
        return None
