"""Умолчание по-видового происхождения для СУЩЕСТВУЮЩИХ строк — не выбрано.

DRF-1929, F1(б). Этот узел КРАСНЫЙ НАМЕРЕННО и красным останется, пока
владелец не ответит. Он не регрессия и не забытая заготовка: он —
названное отсутствие решения, поставленное на место, где иначе решение
подставилось бы молча.

## Почему вопрос вообще есть

Схемная миграция добавляет ``calories_source`` / ``fluids_source`` как
``NULL``-колонки без умолчания: колонка с ``default`` проставила бы
значение каждой существующей строке прямо в DDL, то есть объявила бы
по-видовое происхождение там, где его никто не устанавливал.

Прецедент — ``0017_target_provenance_legacy_backfill``: она отказалась
подписать legacy-ориентиры как ``ayla_calculated``, потому что это
«утверждение, которого мы не можем проверить», и дала им ЧЕСТНОЕ имя
``unknown_legacy``. Тот же вопрос повторяется по видам, и ответ на него
не выводится из кода.

## Три варианта, между которыми выбирает владелец

1. **обе колонки = ``unknown_legacy``** у строк с непустым ориентиром —
   прямое продолжение ``0017``: «происхождение по видам не сохранялось»;
2. **калории = текущее ``targets_source``, жидкость = ``unknown_legacy``** —
   учитывает, что у ``unknown_legacy`` в ``daily_water_ml`` лежит остаток
   СНЯТОЙ формулы ``30 × вес`` (§82), то есть про воду мы знаем БОЛЬШЕ
   плохого, чем про калории;
3. **обе = ``none``** — «ориентира по видам нет»; самый разрушительный:
   ``none`` означает отсутствие ориентира, а ориентир у этих строк есть.

Разница не косметическая: вариант 3 гасит ориентиры живым клиентам,
вариант 2 сохраняет калории и честно обнуляет доверие к воде.

## Почему сторож, а не ``TODO``

``0017`` сама объяснила, чем плохо пустое поле: оно «неотличимо от
«миграция не доехала», и первый же читатель, которому мешает пустота,
заполнит её умолчанием». У нас пустота (``NULL``) есть, и различает её не
значение, а этот узел: пока он красный, вопрос существует и виден в
каждом прогоне. Когда владелец ответит — пишется миграция данных, здесь
проставляется ``DECISION``, и узел становится зелёным.

**До ответа владельца этот PR не сливается.**
"""
from __future__ import annotations

from nutrition.models import NutritionProfile

#: Ответ владельца: один из ``"unknown_legacy_both"``,
#: ``"calories_keep_fluids_legacy"``, ``"none_both"``. ``None`` — не
#: отвечено. Заполняется ВМЕСТЕ с миграцией данных, не раньше: значение
#: здесь без миграции означало бы решение, которое никуда не применено.
DECISION: str | None = None

ALLOWED_DECISIONS = frozenset({
    "unknown_legacy_both",
    "calories_keep_fluids_legacy",
    "none_both",
})


def test_per_kind_backfill_default_is_chosen_by_the_owner():
    """КРАСНЫЙ, пока умолчание для существующих строк не выбрано."""
    assert DECISION is not None, (
        "DRF-1929 F1(б): не выбрано умолчание по-видового происхождения для "
        "СУЩЕСТВУЮЩИХ строк. Схемная миграция добавила calories_source / "
        "fluids_source как NULL — ни одной строке значение не проставлено, и "
        "это сделано намеренно (прецедент 0017: не подписывать тем, чего не "
        "проверили). Варианты: unknown_legacy_both | "
        "calories_keep_fluids_legacy | none_both. Решает владелец; после "
        "ответа — миграция данных + DECISION здесь."
    )
    assert DECISION in ALLOWED_DECISIONS, DECISION


def test_schema_migration_left_existing_rows_untouched():
    """Положительный контроль: колонки есть и умолчания у них нет.

    Красный этого узла означал бы обратное тому, что объявлено: что
    миграция всё-таки что-то проставила. Он зелёный и обязан оставаться
    зелёным до тех пор, пока миграции данных нет.

    Базы этот узел не касается намеренно: проверяется УСТРОЙСТВО поля
    (``null``/``has_default``), а не поведение записи, — поэтому ни
    ``django_db``, ни создания строк здесь нет.
    """
    for name in ("calories_source", "fluids_source"):
        field = NutritionProfile._meta.get_field(name)
        assert field.null is True, f"{name}: ожидался null=True"
        assert not field.has_default(), (
            f"{name}: у поля появилось умолчание — значит DDL проставит его "
            "КАЖДОЙ существующей строке, а это и есть запрещённое «трогать "
            "данные» (DRF-1929: схему делаем, данные не трогаем)."
        )
