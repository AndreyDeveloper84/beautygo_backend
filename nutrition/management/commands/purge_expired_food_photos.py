"""Удаление фотографий еды по сроку (§134/§135, DRF-1651).

Решение владельца §134 (11.09.2026) отменило §132 и назвало единый срок:
**30 суток с момента загрузки**, независимо от того, удалось ли
распознавание и подтвердил ли человек запись. §135 добавил: сырой ответ
распознавателя и временные результаты удаляются **вместе** с фотографией;
остаётся только подтверждённая структурированная запись дневника.

### Почему это команда, а не правило жизненного цикла бакета

Так было раньше, и замер (`docs/MEASURE_FOOD_PHOTO_RETENTION.md`) показал,
чем это кончилось. Утверждение «bucket lifecycle enforces 30-day TTL»
встречается в репозитории **трижды и все три раза прозой**; настроено оно
было **в нуле мест**, включая сам MinIO пилота — проверено 11.09:
«lifecycle configuration does not exist». Четвёртый документ при этом
помечал саму политику незакрытым чекбоксом «нужно подтверждение Privacy».

Три утвердительных упоминания ссылались на неподтверждённое намерение и
цитировали друг друга. §134 поэтому требует прямо: **удаление выполняется
кодом и подтверждается событием аудита либо метрикой**, и **система
обязана выявлять не удалившиеся в срок**.

Правило бакета не умеет ни того, ни другого: оно удаляет молча, и у
приложения нет ни события, ни счётчика, ни способа отличить «удалено» от
«не дошло».

### Почему без ``--apply`` ничего не делает

Как у ``purge_unconsented_body_parameters``: запуск без флага — отчёт о
том, что будет сделано. Необратимое действие требует отдельного слова, а
не отдельного везения.

### Удаление ДВУХШАГОВОЕ, и это главная ловушка задачи

``FileField`` намеренно не трогает объект хранилища при удалении строки —
чтобы не потерять файл при откате транзакции. Значит ``row.delete()``
сам по себе оставляет фотографию в бакете **навсегда и без ссылки на
неё**: строки больше нет, найти объект по базе невозможно.

Это состояние **хуже исходного**, и оно не гипотетическое: на пилоте
11.09 в бакете лежало **семь объектов, которым не соответствует ни одна
строка**. Как они возникли — отдельный вопрос; что они неудаляемы
средствами базы — факт.

Поэтому сначала объект, потом строка. И если объект удалить не удалось —
строка **не трогается**: потерять ссылку на живой файл хуже, чем оставить
просроченную строку до следующего запуска.

### Пять исходов, и «объекта нет» — НЕ успех

```
удалено                объект был и удалён, строка снята
объекта нет ЗДЕСЬ      имя есть, объекта в этом хранилище нет — ОТДЕЛЬНЫЙ счёт
фотографии не было     имя пустое: удалять было нечего и не было никогда
отказ хранилища        причина названа, строка НЕ тронута
объект-сирота          объект есть, строки нет — только перечислить
```

Второй и третий разведены намеренно: «фотография была и куда-то делась»
и «фотографии не существовало» — разные утверждения, и слитые они
сообщали бы об исчезновении снимков, которых не было.

Второй исход считается отдельно ещё и потому, что его легко принять за
успех, а он им не является даже частично: «объекта нет» значит «нет
ЗДЕСЬ». Пилот переехал 03.09, и объекты прежних строк могли остаться в
MinIO брошенной машины.

Отдельного счётчика «объект недостижим» здесь **нет, и это не пропуск**:
изнутри «удалён» и «лежит в другом хранилище» неразличимы. Счётчик,
который никогда не заполнится, хуже честной оговорки — он выглядит
проверкой. Поэтому оговорка печатается текстом рядом с числом.
На пилоте он массовый: пятнадцать строк старше срока ссылаются на файлы,
которых в текущем бакете нет вовсе — пилот переехал 03.09, бакет создан
в тот же день, а самая старая строка от 05.05. Сложить эти пятнадцать с
настоящими удалениями значило бы отчитаться об уничтожении фотографий,
которых команда не видела.

**Сироты не удаляются.** Объект без строки — это либо чужие данные, либо
след аварии; решать их судьбу не команде. Она их перечисляет, и на этом
её полномочия кончаются.

### Что НЕ удаляется никогда

Запись дневника. ``FoodLog.scan`` — ``SET_NULL``, макросы снимаются в
момент записи (``models.py`` «we keep the log because the macros are
already snapshotted»), поэтому удаление скана оставляет дневник целым с
его числами. Это и есть «остаётся подтверждённая структурированная
запись» из §135, и на это стоит положительная стража в тестах: без неё
«просроченных фотографий нет» было бы зелёным и у команды, стирающей
дневник целиком.

### Чего здесь нет намеренно

**Индекса** под запрос «старше срока по всем пользователям». Существующие
``(user, -created_at)`` и ``(tenant, -created_at)`` его не обслуживают, и
индекс нужен — но миграция ``0018`` занята встречным PR #332, который ещё
не слит. Заводить вторую ``0018`` значит устроить конфликт номеров в
очереди. Индекс идёт отдельным PR после #332; при сегодняшних объёмах
(пятнадцать строк) разница неизмерима.

Usage:
    python manage.py purge_expired_food_photos
    python manage.py purge_expired_food_photos --apply
    python manage.py purge_expired_food_photos --scan-orphans
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import timedelta

from django.core.management.base import BaseCommand
from django.utils import timezone

from nutrition.models import FoodScan

#: §134: единый срок с момента ЗАГРУЗКИ. `FoodScan.created_at` —
#: `auto_now_add`, строка создаётся по одному запросу `/scan/` и не
#: зависит ни от успеха распознавания, ни от подтверждения. То есть это
#: и есть момент загрузки, отдельный столбец не нужен.
TTL_DAYS = 30

#: Префикс ключей хранилища — `FoodScan._scan_image_path`.
SCAN_PREFIX = "food-scans"


@dataclass
class Tally:
    """Четыре исхода. Считаются отдельно, потому что значат разное."""

    deleted: int = 0
    object_absent: int = 0
    no_image: int = 0
    refused: list[tuple[int, str]] = field(default_factory=list)
    orphans: list[str] = field(default_factory=list)

    @property
    def not_deleted(self) -> int:
        """Число из §134 — «не удалившиеся в срок».

        Отказы плюс сироты. ``object_absent`` сюда НЕ входит: там строка
        снята и удалять было нечего. Но и к ``deleted`` он не относится —
        у него свой счёт, иначе отчёт об уничтожении фотографий включал
        бы те, которых команда не видела.
        """
        return len(self.refused) + len(self.orphans)


def _known_keys() -> set[str]:
    """Ключи, на которые ссылается хотя бы одна строка — любого возраста.

    Нужны, чтобы отличить сироту от объекта, чья строка ещё не просрочена.
    """
    return {
        name
        for name in FoodScan.objects.exclude(image="").values_list("image", flat=True)
        if name
    }


def find_orphans(storage) -> list[str]:
    """Объекты под ``food-scans/``, на которые не ссылается ни одна строка.

    Обход по одному уровню вложенности: ключ строится как
    ``food-scans/{user_id}/{scan_id}.jpg``. Отдельным флагом, а не всегда:
    на пилоте это семь объектов, но на выросшем бакете полный обход
    стоит денег и времени, и платить их при каждом запуске незачем.
    """
    known = _known_keys()
    found: list[str] = []
    try:
        user_dirs, _ = storage.listdir(SCAN_PREFIX)
    except Exception:  # noqa: BLE001 — хранилище может не уметь listdir
        return found
    for user_dir in user_dirs:
        prefix = f"{SCAN_PREFIX}/{user_dir}"
        try:
            _, files = storage.listdir(prefix)
        except Exception:  # noqa: BLE001
            continue
        for name in files:
            key = f"{prefix}/{name}"
            if key not in known:
                found.append(key)
    return sorted(found)


class Command(BaseCommand):
    help = (
        "Удалить фотографии еды и сырые ответы старше 30 суток (§134/§135). "
        "Без --apply только печатает."
    )

    def add_arguments(self, parser):
        parser.add_argument(
            "--apply",
            action="store_true",
            help=(
                "Выполнить удаление. Без флага команда ничего не меняет — "
                "необратимое действие требует отдельного слова."
            ),
        )
        parser.add_argument(
            "--scan-orphans",
            action="store_true",
            help=(
                "Дополнительно перечислить объекты, на которые не ссылается "
                "ни одна строка. Не удаляет их: судьба объекта без строки — "
                "решение владельца, а не команды."
            ),
        )
        parser.add_argument(
            "--days",
            type=int,
            default=TTL_DAYS,
            help=f"Срок в сутках. По умолчанию {TTL_DAYS} (§134).",
        )

    def handle(self, *args, **options):
        apply = options["apply"]
        days = options["days"]
        cutoff = timezone.now() - timedelta(days=days)

        expired = list(
            FoodScan.objects.filter(created_at__lt=cutoff).order_by("created_at")
        )
        total = FoodScan.objects.count()

        self.stdout.write(
            f"Сканов всего: {total}. Старше {days} сут: {len(expired)}. "
            f"Граница: {cutoff.isoformat()}"
        )

        tally = Tally()

        if options["scan_orphans"]:
            from django.core.files.storage import default_storage

            tally.orphans = find_orphans(default_storage)

        if not expired and not tally.orphans:
            self.stdout.write(self.style.SUCCESS("Удалять нечего."))
            return

        self.stdout.write("")
        self.stdout.write("Будет удалено:" if not apply else "Удаляется:")

        for scan in expired:
            age = (timezone.now() - scan.created_at).days
            head = f"  scan={scan.id} user={scan.user_id} возраст={age} сут"
            has_raw = bool(scan.raw_response)
            logs = scan.food_logs.count()

            if not apply:
                # Печатается ДО удаления и поимённо: «удалили пятнадцать» —
                # утверждение о числе строк, «удалили эти пятнадцать» — о
                # том, что именно ушло.
                self.stdout.write(f"{head}  image={scan.image.name or '—'}")
                self.stdout.write(
                    f"      сырой ответ: {'есть' if has_raw else 'нет'}; "
                    f"записей дневника останется: {logs}"
                )
                continue

            outcome, reason = self._purge_one(scan)
            if outcome == "deleted":
                tally.deleted += 1
                self.stdout.write(f"{head}  удалено (объект + строка)")
            elif outcome == "no_image":
                tally.no_image += 1
                self.stdout.write(f"{head}  строка снята, фотографии не было вовсе")
            elif outcome == "object_absent":
                tally.object_absent += 1
                self.stdout.write(
                    self.style.WARNING(
                        f"{head}  строка снята, объекта НЕТ В ЭТОМ хранилище: "
                        f"{scan.image.name or '—'}"
                    )
                )
            else:
                tally.refused.append((scan.id, reason))
                self.stdout.write(
                    self.style.ERROR(f"{head}  ОТКАЗ, строка не тронута: {reason}")
                )

        self._report(tally, apply, expired, options["scan_orphans"])

    def _purge_one(self, scan: FoodScan) -> tuple[str, str]:
        """Объект, затем строка. Порядок — предмет, а не стиль.

        Обратный порядок оставляет объект в бакете без ссылки на него:
        строки больше нет, найти файл по базе невозможно. Семь таких
        объектов на пилоте уже лежат.
        """
        name = scan.image.name
        if not name:
            # Пятый исход. Строка без фотографии — удалять было НЕЧЕГО, и
            # это не то же самое, что «имя есть, объекта нет»: там
            # фотография была и куда-то делась, здесь её не было никогда.
            # Слив их, отчёт сообщал бы об исчезновении фотографий, которых
            # не существовало.
            scan.delete()
            return "no_image", ""

        try:
            existed = scan.image.storage.exists(name)
            if existed:
                scan.image.delete(save=False)
        except Exception as exc:  # noqa: BLE001 — причина обязана быть названа
            # Строка НЕ трогается: потерять ссылку на живой файл хуже,
            # чем оставить просроченную строку до следующего запуска.
            return "refused", f"{type(exc).__name__}: {exc}"[:200]

        # Сырой ответ уходит вместе со строкой — §135. Отдельно стирать
        # его не нужно: он поле этой же строки.
        scan.delete()
        return ("deleted" if existed else "object_absent"), ""

    def _report(self, tally: Tally, apply: bool, expired: list, scanned: bool) -> None:
        self.stdout.write("")
        if not apply:
            self.stdout.write(
                self.style.WARNING(
                    f"СУХОЙ ПРОГОН. Ничего не изменено. Строк под удаление: "
                    f"{len(expired)}. Запуск с --apply выполнит удаление."
                )
            )
        else:
            self.stdout.write(
                f"Удалено (объект + строка): {tally.deleted}\n"
                f"Строка снята, объекта нет в ЭТОМ хранилище: {tally.object_absent}\n"
                f"Строка снята, фотографии не было вовсе: {tally.no_image}\n"
                f"Отказов хранилища: {len(tally.refused)}"
            )
            if tally.object_absent:
                # Честная формулировка того, что этот счёт НЕ доказывает.
                # «Объекта нет» здесь значит «нет ЗДЕСЬ», а не «удалён»:
                # пилот переехал 03.09, и объекты прежних строк могли
                # остаться в MinIO брошенной машины. Назвать это успехом
                # значило бы отчитаться об удалении, которого никто не видел.
                #
                # Отдельного счётчика «объект недостижим» здесь НЕТ, и это
                # не пропуск: изнутри «удалён» и «лежит в другом хранилище»
                # неразличимы, а счётчик, который никогда не заполнится,
                # хуже честной оговорки — он выглядит проверкой.
                self.stdout.write(
                    self.style.WARNING(
                        "  ^ это НЕ доказательство удаления: объект мог "
                        "остаться в другом хранилище (переезд пилота 03.09). "
                        "Отличить «удалён» от «лежит в другом месте» изнутри "
                        "нельзя — только проверкой прежнего бакета."
                    )
                )

        if scanned:
            self.stdout.write(f"Объектов без строки (сироты): {len(tally.orphans)}")
            for key in tally.orphans:
                self.stdout.write(f"  сирота: {key}")
            if tally.orphans:
                self.stdout.write(
                    self.style.WARNING(
                        "Сироты НЕ удалены: объект без строки — решение "
                        "владельца, а не команды."
                    )
                )
        else:
            # Молчание про сирот не должно читаться как «их нет».
            self.stdout.write(
                "Сироты не искались (--scan-orphans выключен): "
                "их число НЕИЗВЕСТНО, а не ноль."
            )

        # Число §134 печатается последним и отдельно: «выявлять не
        # удалившиеся в срок» — требование о втором счётчике, и счётчик
        # удалённого его не заменяет.
        style = self.style.ERROR if tally.not_deleted else self.style.SUCCESS
        self.stdout.write("")
        self.stdout.write(
            style(f"НЕ УДАЛЕНО В СРОК (§134): {tally.not_deleted}")
        )
