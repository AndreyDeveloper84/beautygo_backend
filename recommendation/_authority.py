class ComponentRole(StrEnum):
    """Роль компонента в конвейере. Ролей четыре, авторитет один.

    `RETRIEVAL` — порождает кандидатов и **вправе иметь свой порядок**.
    Владелец сказал это отдельно: внутреннюю сортировку поиска
    уничтожать не надо. Порядок retrieval — это релевантность выборки,
    а не утверждение о том, что человеку подходит.

    `FILTERING` — сужает множество и **никогда не переупорядочивает по
    смыслу**. Предикат — фильтр, даже если живёт в классе движка.

    `SEMANTIC_RANKING` — единственная роль, создающая Recommendation.
    Принадлежит ровно одному компоненту, и это проверяется сторожем.

    `PRESENTATION` — порядок показа: алфавит, `sort_order`, счётчики.
    Отображение, а не решение.
    """

    RETRIEVAL = "RETRIEVAL"
    FILTERING = "FILTERING"
    SEMANTIC_RANKING = "SEMANTIC_RANKING"
    PRESENTATION = "PRESENTATION"


