"""Реестр авторитетов: кто вправе создавать Recommendation, а кто нет.

Решение владельца (DRF-1628) отняло у остальных компонентов **не право
считать, а право быть конечным ответом Ayla**::

    recommendation_engine
            ↓ candidate generation / signals
    mapping + eligibility
            ↓
    Safety
            ↓
    Canonical Recommendation Resolver
            ↓
    RecommendationDecision

Инвариант, который держится этим модулем::

    SearchResult ≠ CatalogResult ≠ CandidateSet ≠ Recommendation

Непустой Search, Catalog или CandidateSet при **пустой** Recommendation —
допустимое состояние, а не поломка. На «покажи массаж» показываем услуги;
на «что мне лучше выбрать» при нуле подтверждённых связей каталог в
рекомендацию не превращается.

Зачем реестр, если сторож на ранжирование уже есть
--------------------------------------------------

`test_no_ranking_outside_the_resolver` ищет **синтаксис** упорядочивания:
`order_by`, `sorted`, `sort` с признаком качества в аргументах. Он
хорош и уже держит три известных долга.

Но у него есть слепое пятно, и оно измерено, а не предположено. Замер
10.09.2026 тем же гардом::

    users/home_api.py                             мест ранжирования: 0
    ai/…/specialist_context_builder.py            мест ранжирования: 0
    ai/…/recommendation_engine.py                 мест ранжирования: 1

Оба нуля правдивы: эти файлы не сортируют. Они **зовут того, кто
сортирует**, и отдают его порядок дальше как ответ Ayla — один на
главный экран, второй в промпт LLM. Сторож, ищущий сортировку, такого
потребителя не видит по устройству.

Поэтому здесь заведена вторая ось: не «кто сортирует», а **«кто берёт
чужой порядок и выдаёт его за решение»**. Первую ось стережёт
`_ALLOWED`, вторую — `RANKED_OUTPUT_CONSUMERS`.
"""
from __future__ import annotations

from enum import StrEnum

__all__ = [
    "ComponentRole",
    "AUTHORITY_PACKAGE",
    "RANKING_COMPONENTS",
    "RANKED_OUTPUT_CONSUMERS",
    "NON_RANKING_CONSUMERS",
    "ORDER_INHERITING_CONSUMERS",
]


class ComponentRole(StrEnum):
    """Роль компонента в конвейере. Ролей четыре, авторитет один.

    `RETRIEVAL` — порождает кандидатов и **вправе иметь свой порядок**.
    Владелец сказал это отдельно: внутреннюю сортировку поиска
    уничтожать не надо. Порядок retrieval — это релевантность выборки,
    а не утверждение о том, что человеку подходит.

    `FILTERING` — сужает множество и **никогда не переупорядочивает по
    смыслу**. Предикат — фильтр, даже если живёт в классе движка.

    `SEMANTIC_RANKING` — единственная роль, создающая Recommendation.
    Принадлежит ровно одному компоненту, и это проверяется сторожем.

    `PRESENTATION` — порядок показа: алфавит, `sort_order`, счётчики.
    Отображение, а не решение.
    """

    RETRIEVAL = "RETRIEVAL"
    FILTERING = "FILTERING"
    SEMANTIC_RANKING = "SEMANTIC_RANKING"
    PRESENTATION = "PRESENTATION"


#: Единственный носитель роли `SEMANTIC_RANKING`. Путь, а не имя класса:
#: авторитет — это пакет с его гейтом, безопасностью и переписью, а не
#: тип, который можно сконструировать где угодно.
AUTHORITY_PACKAGE = "recommendation/"

#: Компоненты, чей выход упорядочен по признаку качества. Взять их
#: порядок и отдать наружу как ответ Ayla — это и есть подмена
#: авторитета, независимо от того, сортирует потребитель сам или нет.
RANKING_COMPONENTS: dict[str, ComponentRole] = {
    "ai.application.services.recommendation_engine": ComponentRole.RETRIEVAL,
}

#: Потребители, берущие у ранжирующего компонента ИМЕННО ПОРЯДОК.
#: У каждого — задача, которая его снимет. Пустой словарь = вторая ось
#: границы закрыта.
#:
#: Формат тот же, что у `_ALLOWED` в стороже: файл, а не каталог.
#: Каталог прикрыл бы и то, что появится в нём завтра.
RANKED_OUTPUT_CONSUMERS: dict[str, str] = {
    "users/home_api.py": (
        "DRF-1628: главный экран отдаёт `engine.recommend()` как полку. "
        "Понизить движок до стадии конвейера; полка рекомендаций при "
        "NO_VERIFIED_CANDIDATES скрывается или показывает controlled empty "
        "state — остальные полки Home от этого не зависят."
    ),
    "ai/application/services/specialist_context_builder.py": (
        "DRF-1628 (1б): путь ПРОМПТА закрыт — `to_core_specialist_context` "
        "пересобирает список в нейтральный порядок, а мёртвый "
        "`to_prompt_summary()` снят (DRF-1630). Остаётся путь КАРТОЧЕК: "
        "`handle_show_specialists` восстанавливает позицию из локального "
        "контекста, то есть порядок движка, и показывает его клиенту."
    ),
}

#: Потребители порядка движка, которых проверка выше **не видит и не
#: может увидеть**: они не импортируют движок, а читают порядок из уже
#: собранного контекста. Список ведётся руками — это признанный предел
#: сторожа, а не его покрытие.
#:
#: Назван здесь, а не умолчан, по той же причине, по которой заведена
#: сама вторая ось: слепое пятно, о котором написано, — долг; слепое
#: пятно, о котором не написано, — уверенность.
ORDER_INHERITING_CONSUMERS: dict[str, str] = {
    "ai/tools_handlers.py": (
        "DRF-1628 (1б): `handle_show_specialists` восстанавливает порядок "
        "по позиции в `context.candidates`. Сделано это ПРАВИЛЬНО по "
        "намерению — чтобы порядок не выбирала модель, — но восстановленный "
        "порядок принадлежит движку, а не резолверу."
    ),
}

#: Потребители того же компонента, берущие у него НЕ порядок. Исключения
#: постоянные: задачи под ними нет и быть не должно — но названы они
#: поимённо, потому что «зовёт движок» без уточнения, ЧТО берёт, через
#: месяц читается как нарушение и заставляет разбираться заново.
NON_RANKING_CONSUMERS: dict[str, str] = {
    "users/catalog_recommendations_api.py": (
        "берёт только `_goal_category_predicate` — предикат фильтрации, "
        "не порядок. Слои 1 и 2 полки идут через резолвер."
    ),
    "services/goal_coverage.py": (
        "берёт только `len(result.candidates)` — мощность множества, "
        "не порядок. Считает покрытие целей мастерами для экрана подсказок."
    ),
}
