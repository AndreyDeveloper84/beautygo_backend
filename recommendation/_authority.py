"""Реестр авторитетов: кто вправе создавать Recommendation, а кто нет.

Решение владельца (DRF-1628) отняло у остальных компонентов **не право
считать, а право быть конечным ответом Ayla**::

    recommendation_engine
            ↓ candidate generation / signals
    mapping + eligibility
            ↓
    Safety
            ↓
    Canonical Recommendation Resolver
            ↓
    RecommendationDecision

Инвариант, который держится этим модулем::

    SearchResult ≠ CatalogResult ≠ CandidateSet ≠ Recommendation

Непустой Search, Catalog или CandidateSet при **пустой** Recommendation —
допустимое состояние, а не поломка. На «покажи массаж» показываем услуги;
на «что мне лучше выбрать» при нуле подтверждённых связей каталог в
рекомендацию не превращается.

Зачем реестр, если сторож на ранжирование уже есть
--------------------------------------------------

`test_no_ranking_outside_the_resolver` ищет **синтаксис** упорядочивания:
`order_by`, `sorted`, `sort` с признаком качества в аргументах. Он
хорош и уже держит три известных долга.

Но у него есть слепое пятно, и оно измерено, а не предположено. Замер
10.09.2026 тем же гардом::

    users/home_api.py                             мест ранжирования: 0
    ai/…/specialist_context_builder.py            мест ранжирования: 0
    ai/…/recommendation_engine.py                 мест ранжирования: 1

Оба нуля правдивы: эти файлы не сортируют. Они **зовут того, кто
сортирует**, и отдают его порядок дальше как ответ Ayla — один на
главный экран, второй в промпт LLM. Сторож, ищущий сортировку, такого
потребителя не видит по устройству.

Поэтому здесь заведена вторая ось: не «кто сортирует», а **«кто берёт
чужой порядок и выдаёт его за решение»**. Первую ось стережёт
`_ALLOWED`, вторую — `RANKED_OUTPUT_CONSUMERS`.
"""
