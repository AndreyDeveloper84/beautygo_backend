"""S6 — стабильная контролируемая ротация. Контракт §12.

**Перенос, а не новая реализация.** Оригинал — `rotate_ties` / `_rotation_key`
в `ai-bot-platform` `apps/marketplace/discovery.py` (публична и обобщена
протоколом с C-01, #1443). Она уже корректно реализует §12 и решение
владельца §29.6; переписать её значило бы завести второй ключ ротации, а
ключ — это и есть контракт «стабильно внутри человека, равномерно между
людьми». Здесь она приведена к типам резолвера и получила одно уточнение,
которого в оригинале не было: **отсутствие seed не означает алфавит**.

Что изменилось при переносе и почему:

* оригинал сортирует по `(-match_score, rotation_key)`, то есть держит счёт
  внутри себя. Здесь счёта нет вовсе: ярусы уже вычислены конвейером
  лексикографически, и ротация применяется **только внутри яруса** (§12.1).
  Это то же поведение — «ротация не может обогнать стадию, которая
  различила», — но выраженное так, что нарушить его нечем;
* `rotation_seed=None` в оригинале возвращает порядок `("name", "id")`, то
  есть алфавит. По §12.3 отсутствие seed означает «различить нечем», и
  порядок внутри яруса объявляется неопределённым: ротация не применяется,
  а поверхность обязана показать ярус равноправным.
"""
from __future__ import annotations

import hashlib
from typing import Sequence, TypeVar
from uuid import UUID

_T = TypeVar("_T")


def rotation_key(seed: str, candidate_id: UUID) -> bytes:
    """`blake2b(seed || id)` — чистая функция пары и ничего больше.

    Ни часов, ни `random`: оба сломали бы первое свойство — стабильность
    внутри одного контекста, — а его человек как раз замечает (§29.6:
    список не должен перетасовываться между его же репликами).
    """
    return hashlib.blake2b(f"{seed}{candidate_id}".encode(), digest_size=16).digest()


def rotate_within_tier(candidate_ids: Sequence[UUID], seed: str | None) -> list[UUID]:
    """Упорядочить НЕРАЗЛИЧЁННЫХ кандидатов одного яруса.

    При `seed is None` порядок не меняется: различить нечем, и подставлять
    вместо этого любую чистую функцию идентификатора (алфавит, UUID, `id`)
    запрещено — она одинакова для всех людей и на все времена, то есть
    кандидат с «неудачным» именем не показывается никому и никогда
    (канон §9.1, запрет лексикографического fallback при отсечении).
    """
    if seed is None:
        return list(candidate_ids)
    return sorted(candidate_ids, key=lambda cid: rotation_key(seed, cid))
