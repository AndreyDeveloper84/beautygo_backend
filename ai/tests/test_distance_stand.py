"""Стенд фильтрации по расстоянию: проверка до появления настоящих мастеров.

Зачем стенд, если есть тест «ближний выше дальнего»
---------------------------------------------------

Существующий тест (`test_recommendation_engine.py`) проверяет, что при
равном рейтинге ближний обгоняет дальнего. Это верно и мало: он берёт
**двух** мастеров и **одну** пару расстояний, то есть отвечает на
«функция вернула правильное из двух», а не на **«порядок соответствует
расстоянию»**.

Стенд ниже расставляет мастеров по **известным** расстояниям и проверяет
соответствие порядка целиком. Ожидаемый ответ здесь точный, а не
относительный, — тестовые мастера для того и оставлены жить.

Что стенд НЕ проверяет, и почему это сказано вслух
--------------------------------------------------

Он **не может** проверить состояние боевых данных: у него своя база и
свои мастера. Замер 11.09 показал, что на пилоте **31 мастер и 0
координат**, то есть расстояние не различает никого. Приёмка
геокодирования — наблюдение над живыми данными, а не тест; для неё
нужна команда, читающая ту базу, где данные лежат
(`docs/MEASURE_DISTANCE_FILTERING.md`, §6).

Стенд — **инструмент приёмки**: когда координаты появятся, он скажет,
правильно ли работает порядок. Он не скажет, появились ли они.
"""
from __future__ import annotations

from decimal import Decimal as D

import pytest

from ai.application.services.recommendation_engine import (
    RecommendationEngine,
    RecommendationQuery,
)
from ai.tests.factories import make_specialist

pytestmark = pytest.mark.django_db

#: Клиент. Пенза, центр — та же точка, что в существующих тестах движка,
#: чтобы числа сравнивались между файлами.
CLIENT_LAT, CLIENT_LON = 53.2007, 45.0046

#: Сдвиг по широте, дающий примерно километр. 1° широты ≈ 111 км.
#: Долгота не годится: её километр зависит от широты, и на стенде это
#: превратилось бы в скрытую переменную.
DEG_PER_KM = 1.0 / 111.0


def _at_km(km: float, *, name: str, rating: float = 4.8):
    """Мастер на заданном расстоянии СЕВЕРНЕЕ клиента.

    Только по широте: так расстояние считается из одного числа и его
    можно назвать в имени теста. Смешение широты с долготой дало бы тот
    же километраж, но проверять пришлось бы арифметику фикстуры.
    """
    s = make_specialist(display_name=name, rating=rating, reviews_count=50)
    s.location_lat = D(str(CLIENT_LAT + km * DEG_PER_KM))
    s.location_lng = D(str(CLIENT_LON))
    s.save()
    return s


def _order(engine: RecommendationEngine, **query):
    result = engine.recommend(
        RecommendationQuery(
            client_lat=CLIENT_LAT, client_lon=CLIENT_LON, limit=10, **query,
        ),
        use_cache=False,
    )
    return [c.display_name for c in result.candidates]


# ---------------------------------------------------------------------------
# Порядок соответствует расстоянию
# ---------------------------------------------------------------------------


def test_order_follows_distance_for_five_masters():
    """Пятеро на известных расстояниях выстраиваются по возрастанию.

    Пять, а не два: пара проверяет «который из двух», цепочка —
    **монотонность**. Ошибка в знаке или в делении на порог пару
    пройдёт, а цепочку нет.

    Рейтинг у всех одинаковый: расстояние должно решать в одиночку.
    """
    for km, name in ((12, "12км"), (3, "3км"), (20, "20км"), (1, "1км"), (7, "7км")):
        _at_km(km, name=name)

    engine = RecommendationEngine(max_distance_km=25.0)
    assert _order(engine) == ["1км", "3км", "7км", "12км", "20км"]


def test_beyond_the_threshold_everyone_is_equal():
    """За порогом расстояние перестаёт быть признаком вовсе.

    Это не «шкала затухает», а **исчезновение признака**: 30 км и
    300 км дают одинаковый ноль. Проверяется рейтингом — если бы
    расстояние ещё различало, порядок определило бы оно, а не он.

    Замер 11.09: порог на пилоте `max_distance_km = 25`.
    """
    _at_km(30, name="Дальний, но получше", rating=4.9)
    _at_km(300, name="Очень дальний, похуже", rating=4.1)

    engine = RecommendationEngine(max_distance_km=25.0)
    assert _order(engine) == ["Дальний, но получше", "Очень дальний, похуже"]


# ---------------------------------------------------------------------------
# При равном расстоянии решает следующий признак, а не случайность
# ---------------------------------------------------------------------------


def test_equal_distance_is_broken_by_the_next_weight_not_by_chance():
    """Одинаково близкие упорядочены рейтингом.

    Требование сформулировано главным окном отдельно от порядка: при
    равном расстоянии выбор обязан делать **следующий по весу
    признак**, а не порядок строк в базе.
    """
    _at_km(5, name="Похуже", rating=4.2)
    _at_km(5, name="Получше", rating=4.9)

    engine = RecommendationEngine(max_distance_km=25.0)
    assert _order(engine) == ["Получше", "Похуже"]


def test_the_same_input_gives_the_same_order_twice():
    """Порядок воспроизводим между вызовами.

    Положительная стража к предыдущему тесту: «решает рейтинг» можно
    зеленить и на порядке, который просто СЕГОДНЯ совпал. Устойчивость
    проверяется повтором, а не верой в детерминизм ORM.

    Кэш выключен намеренно: он дал бы тот же ответ, не доказав ничего.
    """
    for km, name, rating in ((5, "А", 4.5), (5, "Б", 4.5), (5, "В", 4.5)):
        _at_km(km, name=name, rating=rating)

    engine = RecommendationEngine(max_distance_km=25.0)
    assert _order(engine) == _order(engine)


