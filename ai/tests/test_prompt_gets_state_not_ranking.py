"""Промпт получает состояние, а не чужое ранжирование (DRF-1630).

Роль бота по решению владельца — **language rendering**: он облекает в
слова уже принятое состояние, а не решает, что сказать. Отсюда два
требования, и первое было нарушено способом, который не ищется грепом.

Как ранжирование доходило до речи
---------------------------------

Не числами, а **позицией**. Ядро печатает в промпт `master_id`, имя и
услуги — ни рейтинга, ни расстояния, ни балла (это уже было сделано
раньше, канон §8). Но печатает **в порядке списка**, а список приходил
из движка отсортированным по composite. Модель читает сверху вниз и
первого называет лучшим.

Поэтому проверка ниже смотрит не на текст промпта, а на **порядок**: он
обязан не совпадать с порядком движка и обязан быть воспроизводимым.

Что промпт получает, когда кандидатов нет
-----------------------------------------

Раньше — фразу ядра «нет активных мастеров, записаться можно только
через менеджера». Она про АКТИВНОСТЬ, состояния не называет и уводит к
менеджеру. Модель, получив её, дальше сочиняла сама.

Теперь — машинно-читаемое имя состояния и список разрешённых
продолжений. Молчание запрещено отдельно: отсутствие рекомендации не
равно отсутствию пользы.

Почему `NO_CANDIDATES`, а не `NO_VERIFIED_CANDIDATES`
-----------------------------------------------------

Второе — состояние резолвера, и оно утверждает, что проверка связей
была. Сегодня промпт собирается мимо резолвера, и пусто здесь значит
«движок после фильтров не вернул никого». Назвать это
`NO_VERIFIED_CANDIDATES` значило бы приписать системе шаг, которого она
не делала. Последний тест файла сторожит именно это.
"""
from __future__ import annotations

import uuid
from decimal import Decimal

import pytest

from ai.application.services.specialist_context_builder import (
    SpecialistCandidate as LocalCandidate,
    SpecialistContext as LocalContext,
)
from ai.concierge_factory import (
    EMPTY_CANDIDATES_PROMPT_STATE,
    to_core_specialist_context,
)

TENANT = "tenant-1630"


def _local(names: list[str]) -> LocalContext:
    """Локальный контекст в ПОРЯДКЕ ДВИЖКА — как он приходит на вход.

    Имена нарочно даны в порядке, обратном алфавитному: если бы функция
    просто сохраняла вход, тест на нейтральный порядок зеленел бы
    случайно.
    """
    return LocalContext(
        candidates=[
            LocalCandidate(
                id=uuid.uuid5(uuid.NAMESPACE_DNS, name),
                display_name=name,
                rating=Decimal("5.0"),
                reviews_count=1,
                address="",
                distance_km=None,
                services_preview=[],
                match_reasons=[],
            )
            for name in names
        ],
    )


# ---------------------------------------------------------------------------
# Порядок движка в промпт не проходит
# ---------------------------------------------------------------------------


def test_prompt_order_is_not_the_engine_order():
    """Порядок, пришедший от движка, до промпта не доезжает.

    Вход дан в порядке движка «Яна, Борис, Анна». Если бы функция
    сохраняла его, первой в промпте оказалась бы Яна — и модель назвала
    бы лучшей её, не имея на то никакого основания, кроме позиции.
    """
    core = to_core_specialist_context(
        _local(["Яна", "Борис", "Анна"]), tenant_id=TENANT,
    )
    assert [c.name for c in core.candidates] != ["Яна", "Борис", "Анна"]


def test_prompt_order_is_neutral_and_reproducible():
    """Порядок алфавитный: человек читает список, а не рейтинг.

    Обе величины — имя и `id` — несемантичны, но UUID-порядок выглядел
    бы случайным и провоцировал вопрос «почему этот первый», у которого
    нет ответа. Воспроизводимость проверяется отдельно: порядок обязан
    совпадать между вызовами, иначе выдача плавала бы между репликами.
    """
    first = to_core_specialist_context(_local(["Яна", "Борис", "Анна"]), tenant_id=TENANT)
    second = to_core_specialist_context(_local(["Анна", "Яна", "Борис"]), tenant_id=TENANT)

    assert [c.name for c in first.candidates] == ["Анна", "Борис", "Яна"]
    assert [c.name for c in second.candidates] == ["Анна", "Борис", "Яна"]


def test_reordering_does_not_drop_anyone():
    """Положительная стража: пересборка списка никого не теряет.

    Без неё тест на «порядок не тот» зеленел бы и на функции, которая
    возвращает пустой список: он тоже не равен порядку движка.
    """
    local = _local(["Яна", "Борис", "Анна"])
    core = to_core_specialist_context(local, tenant_id=TENANT)

    assert len(core.candidates) == len(local.candidates)
    assert {c.id for c in core.candidates} == {c.id for c in local.candidates}
    assert core.candidate_ids == {c.id for c in local.candidates}


# ---------------------------------------------------------------------------
# Пусто — это состояние с именем, а не фраза про менеджера
# ---------------------------------------------------------------------------


def test_empty_context_carries_a_named_state():
    """Пустому случаю дано имя, которое модель может отличить."""
    core = to_core_specialist_context(_local([]), tenant_id=TENANT)
    assert "STATE=NO_CANDIDATES" in core.summary_text


def test_empty_context_lists_the_allowed_continuations():
    """Молчание запрещено: отсутствие рекомендации ≠ отсутствие пользы.

    Четыре продолжения названы владельцем дословно. Проверяются все
    четыре, а не факт непустой строки: «что-то написано» зеленело бы и
    на прежней фразе про менеджера.
    """
    text = to_core_specialist_context(_local([]), tenant_id=TENANT).summary_text
    for continuation in ("показать каталог", "уточнить запрос",
                         "начать заново", "выбрать самостоятельно"):
        assert continuation in text, f"не названо разрешённое продолжение: {continuation}"


def test_empty_context_no_longer_sends_the_client_to_a_manager():
    """Прежняя фраза ядра ушла.

    Она про активность мастеров, а не про состояние подбора, и вела
    человека к менеджеру там, где продукт мог предложить каталог.
    """
    text = to_core_specialist_context(_local([]), tenant_id=TENANT).summary_text
    assert "менеджера" not in text


def test_the_state_does_not_claim_a_verification_that_did_not_happen():
    """`NO_VERIFIED_CANDIDATES` здесь не пишется, и это не описка.

    Это имя состояния резолвера: оно утверждает, что проверка связей
    была и подтверждённых не нашлось. Сегодня промпт собирается мимо
    резолвера — проверки не было вовсе. Приписать её значило бы
    повторить подмену «связи ещё нет» против «связи не будет» (§93),
    только на другом слое.

    **Решение владельца В-13, дословно:** состояние не вправе утверждать,
    что стадия конвейера произошла, если она не происходила; и
    `NO_CANDIDATES` не «исправлять» на `NO_VERIFIED_CANDIDATES` до того,
    как канонический резолвер и гейт маппинга действительно отработают.

    То есть этот тест — исполнение решения, а не предосторожность
    автора.

    **Кто и когда вправе его снять.** Только тот, кто проведёт
    `recommendation_status` явным полем (В-16): тогда имя перестанет
    собираться здесь и приедет от резолвера, а сторож станет не нужен
    по существу. Снимать его «за ненадобностью» раньше нельзя — именно
    так он и снимется, если не написать этого прямо: тест, чьё условие
    не выполнено, выглядит одинаково с тестом, чьё условие выполнено.

    В коммите, который его снимает, обязана быть строка «поле проведено,
    имя приходит от резолвера» — иначе снятие неотличимо от уборки.
    """
    assert "NO_VERIFIED_CANDIDATES" not in EMPTY_CANDIDATES_PROMPT_STATE


# ---------------------------------------------------------------------------
# Мёртвый метод снят
# ---------------------------------------------------------------------------


@pytest.mark.parametrize(
    "module_name",
    [
        "ai.application.services.specialist_context_builder",
        "ai.application.services.recommendation_engine",
    ],
)
def test_the_ranked_prompt_summary_is_gone(module_name):
    """`to_prompt_summary` не должен существовать ни в одном из двух мест.

    Вызовов у него не было ни одного — и именно поэтому он был опасен:
    готовый метод, кладущий ★рейтинг и расстояние в промпт, это
    приглашение подключить его снова. Владелец назвал находку **классом
    дефекта, а не багом**, и сторож здесь сторожит класс: метод не
    должен вернуться под тем же именем.
    """
    import importlib

    module = importlib.import_module(module_name)
    for obj_name in dir(module):
        obj = getattr(module, obj_name)
        if isinstance(obj, type):
            assert not hasattr(obj, "to_prompt_summary"), (
                f"{module_name}.{obj_name}.to_prompt_summary вернулся"
            )
