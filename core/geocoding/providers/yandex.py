"""Яндекс Геокодер — заглушка, и заглушка намеренно, с суммой в тексте.

§139 называет Яндекс прямо. Исследование карт (11.09.2026,
``RESEARCH_MAPS_DISTANCE_2026-09-11.md`` §2) показало, чего §139 в момент
принятия не знал:

* **бесплатный тариф запрещает хранить координаты у себя** — только кэш
  ≤30 дней и только вместе с показом карты Яндекса. §139 требует ровно
  хранения: восемь полей на ``Tenant``;
* тариф с правом хранения — **226 200 ₽/год**; без права — 195 000 ₽/год.

Владелец: «карты очень дорого, поищи бесплатные или хотя бы не такие
дорогие». Это его слово против буквы §139, и оно внесено в реестр решений
как амендмент с ценой.

Заглушка существует, чтобы следующий, кто откроет этот файл с намерением
«дописать», прочитал сумму раньше, чем ключ. Если владелец купит расширенную
лицензию — реализация сюда, имя ``yandex`` уже зарезервировано в
``Tenant.geocode_provider``.
"""
from __future__ import annotations

from core.geocoding.contract import GeocodeResult, Outcome

LICENCE_NOTE = (
    "Яндекс Геокодер не реализован намеренно: бесплатный тариф запрещает "
    "хранить координаты (кэш ≤30 дней, только с картой Яндекса), а §139 "
    "требует хранения. Тариф с правом хранения — 226 200 ₽/год; владелец "
    "отверг 11.09.2026. Реализовывать только после покупки лицензии."
)


class YandexGeocoder:
    name = "yandex"

    def check(self) -> GeocodeResult | None:
        # Отказ ДО первого вызова, с причиной для человека. Не исключение:
        # команда печатает причину и выходит с кодом 2, как и на любой
        # другой неготовности провайдера.
        return GeocodeResult(outcome=Outcome.MISCONFIGURED, provider=self.name, reason=LICENCE_NOTE)

    def geocode(self, address: str) -> GeocodeResult:
        raise NotImplementedError(LICENCE_NOTE)
