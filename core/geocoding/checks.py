"""Системные проверки геокодирования: механизм не притворяется живым.

**Две проверки, два пути, два разных последствия.** Ниже — обратное
геокодирование (DRF-1685, ``geocoding.W001/E001``), в конце файла — прямое,
геокодирование МЕСТ (DRF-2028, ``geocoding.W002``). Они намеренно не
объединены и не глушат друг друга: при пустом ключе одного провайдера
заговорят обе, и это правда, а не дубль — цена падает на ``default``, места
остаются без координат, и лечится это независимо (см. докстринг
``places_geocoding_is_not_a_fiction``).

---

Обратное геокодирование не притворяется живым (DRF-1685).

Три месяца региональная цена по координатам «работала»: функция была,
тесты зелёные, а ключ существовал только в тестах — в бою всегда пусто,
всегда ``default``, и ни одна строка об этом не говорила. Механизм
построен и выключен — это **третье состояние**, и оно обязано быть видно.

Проверка запускается на каждом ``manage.py check / migrate / runserver``:

* провайдер настроен — молчит;
* не настроен и ``GEOCODING_REQUIRE_LIVE_REVERSE = False`` — **Warning**
  ``geocoding.W001``: состояние названо, запуск не блокируется;
* не настроен и ``= True`` («функция объявлена живой») — **Error**
  ``geocoding.E001``: ровно сторож из тикета — краснеет, когда ключа нет, а
  функция объявлена живой.

Проверка не ходит в сеть: она читает то же, что читает ``check()``
провайдера, — настройки.
"""
from __future__ import annotations

from django.conf import settings
from django.core.checks import Error, Warning, register

from core.geocoding.providers import PROVIDERS, get_provider
from services.geocoding import reverse_geocoding_readiness

#: Куда смотреть человеку, чтобы узнать, ИЗ ЧЕГО выбирать. Два адреса вместо
#: перечисления имён — и это не стилистика: перечисление положило бы имена
#: провайдеров в ЭТОТ файл, а сторож закрытого списка
#: (``core/tests/test_geocoding_contract.py``, узел
#: ``test_the_set_of_modules_that_talk_to_geocoders_is_closed``) ищет их по
#: тексту и записал бы модуль в «ходящие к геокодерам». Он ни к кому не ходит;
#: ослабить сторож ради собственного прохода нельзя.
_REGISTRY_HINT = (
    "Выберите провайдера из реестра и задайте его ключ или хост. Реестр — "
    "core/geocoding/providers/__init__.py; имена печатает "
    "`manage.py geocode_locations --help`."
)


@register()
def reverse_geocoding_is_not_a_fiction(app_configs, **kwargs):
    reason = reverse_geocoding_readiness()
    if reason is None:
        return []
    msg = (
        f"Обратное геокодирование (региональная цена по координатам) не настроено: "
        f"{reason}. Пока так — региональная цена по координатам всегда default."
    )
    if getattr(settings, "GEOCODING_REQUIRE_LIVE_REVERSE", False):
        return [Error(msg, hint="Задайте ключ провайдера или снимите GEOCODING_REQUIRE_LIVE_REVERSE.",
                      id="geocoding.E001")]
    return [Warning(msg, hint="Это известное состояние (DRF-1685), а не сбой.", id="geocoding.W001")]


def places_geocoding_readiness() -> str | None:
    """``None`` — хотя бы один провайдер реестра готов; иначе причины по всем.

    Предикат по РЕЕСТРУ, а не по ``GEOCODING_PROVIDER``. Та настройка
    объявлена (`djangoProject/settings/base.py:767`) для **обратного**
    геокодирования; прямой путь — ``geocode_locations`` — берёт провайдера из
    обязательного аргумента ``--provider`` и её не читает вовсе. Сторож на ней
    утверждал бы готовность того, чего прямой путь не касается: верное
    утверждение не о том, то есть ровно дефект, ради которого заведён DRF-2028.

    Достаточно ОДНОГО готового: места смогут получить координаты, каким бы
    именем ни запустили прогон.

    Причины берутся из ``check()`` самих провайдеров, а не пересказываются —
    поэтому в тексте видно, какую настройку заполнить. Сети нет: ``check()``
    обязан отвечать до первого запроса (`core/geocoding/providers/base.py`).
    """
    reasons = []
    for name in sorted(PROVIDERS):
        refusal = get_provider(name).check()
        if refusal is None:
            return None
        reasons.append(f"{name} — {refusal.reason}")
    return "; ".join(reasons)


@register()
def places_geocoding_is_not_a_fiction(app_configs, **kwargs):
    """Геокодирование мест построено и выключено — состояние названо (DRF-2028).

    Механизм есть целиком: адаптер, провайдеры, путь записи, команда. Команда
    отказывается честно (`tenants/management/commands/geocode_locations.py:103-107`,
    «ни одного запроса не сделано»), но **только когда её запустят**. Пока её
    не запускают, состояние невидимо — и это то самое третье состояние, ради
    которого писалась сестринская проверка выше.

    **Почему рядом с W001, а не вместо неё.** При пустом ключе одного
    провайдера заговорят обе. Они называют разные последствия (цена всегда
    ``default`` против «у мест не появятся координаты») и гаснут независимо:
    настроенный хост второго провайдера гасит эту, а W001 продолжит говорить,
    пока ``GEOCODING_PROVIDER`` указывает на ненастроенного — и это правда, а
    не шум. Объединение свело бы одно сообщение к описанию соседнего пути —
    ровно тот дефект, который здесь и чинится.

    Ошибочного состояния у этой проверки нет намеренно: «объявлено живым»
    (``GEOCODING_REQUIRE_LIVE_REVERSE``) относится к обратному пути. У прямого
    такого объявления не существует, и выдумывать его в сторожe нельзя.
    """
    reason = places_geocoding_readiness()
    if reason is None:
        return []
    msg = (
        "Геокодирование мест оказания услуг не настроено ни одним провайдером "
        f"реестра: {reason}. Пока так — у мест не появятся координаты: "
        "geocode_locations откажет до первого запроса, а места останутся без "
        "широты и долготы."
    )
    return [Warning(msg, hint=_REGISTRY_HINT, id="geocoding.W002")]
